/**
 * Чистые правила, которыми редактор согласован с бэкендом. Держатся
 * отдельно от React и от TipTap: их проверяют вызовом, а не рендером.
 */

/**
 * Схемы, которые переживают чистку `Safelist.relaxed()` в атрибуте `href`.
 *
 * Список не наш: он записан в jsoup (`addProtocols("a", "href", "ftp",
 * "http", "https", "mailto")`) и повторён здесь потому, что проверять
 * адрес надо **до** сохранения. Отправленная схема `tel:` не ломает
 * запись — бэкенд молча снимает у ссылки `href`, и в статье остаётся
 * подчёркнутый текст, который никуда не ведёт. Модератор узнал бы об этом
 * от посетителя.
 */
const ALLOWED_SCHEMES = ['http:', 'https:', 'mailto:', 'ftp:'] as const;

/** Что показать в строке ввода адреса, когда схема не переживёт сохранения. */
const SCHEME_REFUSAL =
  'Такой адрес не сохранится. Годятся http, https, mailto, ftp, ' +
  'адрес внутри портала (/about/news) и якорь (#раздел)';

export type HrefCheck = { href: string } | { error: string };

/**
 * Разбор адреса, введённого модератором.
 *
 * Три случая проходят как есть: адрес внутри портала (`/about/news` —
 * такие ссылки лежат в перенесённых текстах и уводят в роутер), якорь
 * и полный адрес с разрешённой схемой. Адрес без схемы (`stankin.ru`)
 * дополняется `https://` — так же, как это делает автоссылка TipTap
 * при наборе. Всё остальное — отказ с объяснением.
 *
 * `//example.com` внутренним **не** считается: это протоколонезависимый
 * внешний адрес, и роутер увёл бы по нему на несуществующий путь портала.
 * Схема ему дописывается, как и адресу без неё. То же правило записано
 * в `shared/ui/Markdown.tsx`, где ссылки чужого текста делятся
 * на внутренние и внешние.
 */
export function checkHref(input: string): HrefCheck {
  const value = input.trim();

  if (value === '') return { error: 'Укажите адрес ссылки' };

  if (value.startsWith('#')) return { href: value };

  if (value.startsWith('//')) return { href: `https:${value}` };

  if (value.startsWith('/')) return { href: value };

  const scheme = value.match(/^[a-z][a-z0-9+.-]*:/i)?.[0].toLowerCase();

  if (scheme === undefined) return { href: `https://${value}` };

  return ALLOWED_SCHEMES.includes(scheme as (typeof ALLOWED_SCHEMES)[number])
    ? { href: value }
    : { error: SCHEME_REFUSAL };
}

/**
 * Годится ли адрес для ссылки — тем же правилом, что и `checkHref`,
 * но без починки и без текста отказа.
 *
 * Нужен расширению `Link`: оно спрашивает про каждый адрес и при разборе
 * чужого HTML, и при вставке. Без этого редактор согласился бы на `tel:`
 * и `javascript:` — первое молча теряет `href` на сохранении, второе
 * вырезает санитайзер.
 */
export function isAllowedHref(input: string): boolean {
  return 'href' in checkHref(input);
}

/**
 * Пуст ли сохранённый HTML.
 *
 * Пустой документ TipTap сериализуется в `<p></p>`, а не в пустую строку,
 * и без этой проверки незаполненное поле уехало бы в базу абзацем
 * из ничего. Для контракта это разница между «не заполнено» и «заполнено
 * пустотой»: `emptyToNull` смотрит именно на пустую строку, а бэкенд
 * на rich-text полях требует непустоты **после** чистки — то есть `<p></p>`
 * в обязательном поле даст `400`, а в необязательном осядет в базе мусором,
 * из-за которого раздел на карточке ППС нарисуется пустой плашкой.
 *
 * Разбор строкой, а не `editor.isEmpty`: значение приходит и снаружи —
 * из ответа сервера, где такой абзац мог остаться от прежних правок.
 */
export function isEmptyHtml(html: string): boolean {
  return html.replace(/<(p|br)\s*\/?>|<\/p>|&nbsp;|\s/gi, '') === '';
}
