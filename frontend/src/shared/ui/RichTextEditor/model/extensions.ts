import Image from '@tiptap/extension-image';
import Strike from '@tiptap/extension-strike';
import Subscript from '@tiptap/extension-subscript';
import Superscript from '@tiptap/extension-superscript';
import StarterKit from '@tiptap/starter-kit';

import { isAllowedHref } from '../lib/html';

/**
 * Схема редактора, подогнанная под белый список бэкенда.
 *
 * Правило, из которого выведено всё ниже: **что редактор умеет, то должно
 * пережить сохранение, и что лежит в базе, то редактор обязан открыть
 * без потерь.** Обе половины нарушаются молча.
 *
 * Первая — тегами, которых нет в `Safelist.relaxed()`: их `Jsoup.clean`
 * разворачивает, оставляя текст. Кнопка при этом работает, курсив в поле
 * виден, а на странице его нет — и жалоба приходит от посетителя, а не
 * от модератора.
 *
 * Вторая — тегами, которых нет в схеме TipTap: их выбрасывает разбор
 * при открытии формы. Модератор правит заголовок новости, сохраняет,
 * и вместе с заголовком уезжают картинки, которых он не трогал.
 *
 * Что из этого следует по пунктам — в комментариях к каждому расширению.
 * Список тегов сверен с исходником jsoup 1.23.2, `Safelist.relaxed()`.
 */
export const richTextExtensions = [
  StarterKit.configure({
    /*
     * `<hr>` в белом списке нет. Кнопка «разделитель» рисовала бы линию,
     * которую сохранение стирает, поэтому расширение выключено целиком:
     * иначе черта приезжала бы ещё и по Markdown-вводу «---».
     */
    horizontalRule: false,

    /*
     * Пустой абзац в конце документа. Нужен он затем, чтобы после
     * картинки последним блоком можно было поставить курсор, — но
     * приезжает он и в сохраняемый HTML, то есть каждая запись копит
     * по `<p></p>` за правку. Курсор после картинки ставит `gapcursor`
     * из того же набора, он остаётся включённым.
     */
    trailingNode: false,

    /*
     * Своя реализация, ниже: штатная рисует `<s>`, а его в белом списке
     * нет — есть только `<strike>`.
     */
    strike: false,

    link: {
      /*
       * Клик по ссылке в поле ввода уводил бы модератора со страницы —
       * вместе с несохранённой формой. Внутри редактора ссылка нужна
       * как разметка, а не как ссылка.
       */
      openOnClick: false,
      /*
       * Адрес без схемы дополняется `https`, а не `http`: портал живёт
       * по https, и набранный «stankin.ru» не должен становиться ссылкой
       * на незашифрованный адрес.
       */
      defaultProtocol: 'https',
      /*
       * Штатный список схем шире белого списка бэкенда — в нём есть
       * `tel`, `sms`, `xmpp`. Такая ссылка теряет `href` при сохранении
       * и превращается в текст, который никуда не ведёт.
       */
      isAllowedUri: (url: string) => isAllowedHref(url),
      /*
       * Штатные `target="_blank"` и `rel="noopener noreferrer nofollow"`
       * сняты: у тега `a` белый список разрешает только `href` и `title`,
       * остальное вырезается. Оставленные, они выглядели бы работающей
       * настройкой, которой нет, и уезжали бы в запрос лишними байтами.
       *
       * Именно `null`, а не пустой объект: `configure` не заменяет
       * настройки, а сливает их с умолчаниями, и пустым объектом атрибуты
       * не снимаются (поймано тестом). `null` ProseMirror при рендере
       * пропускает.
       */
      HTMLAttributes: { target: null, rel: null, class: null },
    },
  }),

  /**
   * Зачёркивание тегом `<strike>`.
   *
   * `Safelist.relaxed()` знает `strike` и не знает ни `s`, ни `del`.
   * Штатное расширение рисует `<s>`, поэтому зачёркнутый текст доезжал
   * бы до базы обычным: тег разворачивается, буквы остаются. Разбор
   * при этом не трогаем — он принимает все три написания, и старый текст
   * с `<s>` или `<del>` открывается зачёркнутым, а сохраняется уже
   * в том виде, который переживёт чистку.
   */
  Strike.extend({
    renderHTML({ HTMLAttributes }) {
      return ['strike', HTMLAttributes, 0];
    },
  }),

  /*
   * Картинки. Разбор нужен любому полю: без расширения открытая на правку
   * новость теряла бы все `<img>`, которые в ней уже есть. Вставка —
   * через загрузку в `POST /api/files` (`useImageForm`), и только у поля,
   * которому форма назвала раздел хранилища.
   *
   * `allowBase64` остаётся выключенным (значение по умолчанию): картинка
   * `data:`-адресом не пережила бы сохранение — белый список разрешает
   * у `img` только `http`, `https` и относительный адрес. Файл из буфера
   * обмена поэтому идёт не в документ, а в ту же загрузку
   * (`useRichTextEditor`, `handlePaste`).
   */
  Image,

  /*
   * Верхний и нижний индекс: оба тега в белом списке есть, и оба были
   * в панели старого Quill — значит встречаются в перенесённых текстах.
   */
  Subscript,
  Superscript,
];
