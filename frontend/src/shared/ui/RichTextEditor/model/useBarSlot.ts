import { useState } from 'react';

/** Какая строка ввода занимает место под панелью. */
export type BarKind = 'link' | 'image';

/**
 * Место под панелью — одно, и занимает его одна строка.
 *
 * Правило приходится держать состоянием, а не парой независимых флагов
 * у каждой строки: открыть строку можно четырьмя разными путями — кнопкой
 * панели, диалогом выбора файла, вставкой из буфера, перетаскиванием, —
 * и «закрой соседа» пришлось бы помнить в каждом из них. Забытое в одном,
 * оно давало бы два поля ввода подряд, где непонятно, к чему относится
 * «Применить».
 *
 * Заодно из этого состояния видно, закрылось ли место целиком: возврат
 * курсора в текст (`useFocusOnClose`) должен срабатывать на закрытии,
 * но **не** на смене одной строки другой.
 */
export function useBarSlot() {
  const [open, setOpen] = useState<BarKind | null>(null);

  return {
    /** Что открыто; `null` — место свободно. */
    open,
    isOpen: (kind: BarKind) => open === kind,
    show: (kind: BarKind) => setOpen(kind),
    hide: () => setOpen(null),
  };
}
