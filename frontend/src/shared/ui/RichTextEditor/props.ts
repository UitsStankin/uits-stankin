import type { FileCategory } from '@shared/types';

/**
 * Пропсы поля — отдельным модулем, потому что их знают оба: обёртка
 * с `lazy()` и сам редактор.
 *
 * Тип можно было бы взять и прямо из `Editor.tsx` — `import type`
 * компилятор стирает, и куска бы это не притащило. Но разница между
 * `import type` и обычным импортом здесь стоит 131 КБ gzip на каждой
 * странице портала, и полагаться на то, что её заметят при следующей
 * правке, не хочется.
 */
export interface RichTextEditorProps {
  /** Идентификатор поля: от него считаются `id` подписи и сообщения об ошибке. */
  id: string;
  label: string;
  /** Готовый HTML. Пустое поле — это `''`, а не `<p></p>`. */
  value: string;
  onChange: (html: string) => void;
  /** Текст ошибки под полем; `undefined` — ошибки нет. */
  error?: string;
  /** Идёт сохранение: править нельзя, панель погашена. */
  disabled?: boolean;
  /**
   * Раздел хранилища, куда уходят картинки этого поля (`POST /api/files`,
   * `category`): `news` у новостей и конференций, `achievements`
   * у достижений. Задан — в панели есть «Картинка», а файл из буфера
   * обмена или с рабочего стола уходит в загрузку. Не задан — картинок
   * в поле не вставить, хотя уже лежащие в тексте редактор бережёт.
   *
   * Раздел выбирает форма, а не редактор, потому что от раздела зависят
   * права: `avatars` открыт любому вошедшему, остальные — админу
   * и модератору. Преподаватель в своём кабинете грузить в `news`
   * не может, и кнопка у него обещала бы то, что кончится `403`.
   */
  imageCategory?: FileCategory;
}
