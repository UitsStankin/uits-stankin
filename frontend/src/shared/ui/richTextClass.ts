import { cn } from '@shared/lib';

/**
 * Типографика чужого текста — одна на весь портал.
 *
 * `prose` из `@tailwindcss/typography`: у разметки, пришедшей из базы,
 * своих классов нет, а сброс Tailwind снимает стили с `h2`, `ul`
 * и `blockquote` — без него текст выглядит одним сплошным абзацем.
 * `max-w-none`: ширину держит карточка, а не типографика.
 *
 * Строка вынесена в отдельный модуль, потому что мест, где она нужна, стало
 * четыре: статья новости, плашки карточки ППС, Markdown редактируемого
 * раздела и — с F-41 — поле редактора. У последнего причина не «чтобы
 * не повторяться»: редактор показывает то, что увидит посетитель,
 * и разошедшаяся типографика означала бы, что модератор правит один текст,
 * а публикует другой.
 *
 * Своим файлом, а не экспортом из `RichText.tsx`, — из-за
 * `react-refresh/only-export-components`: файл с компонентом не должен
 * экспортировать ничего, кроме компонентов, иначе горячая перезагрузка
 * перестаёт работать для всего модуля.
 */
export const richTextClass = cn(
  'prose prose-sm max-w-none',
  'prose-headings:text-text-heading prose-a:text-primary prose-img:rounded',
);
