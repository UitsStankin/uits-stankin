import { Link } from 'react-router';
import ReactMarkdown, { type Components } from 'react-markdown';
import remarkGfm from 'remark-gfm';

import { cn } from '@shared/lib';

interface MarkdownProps {
  /** Исходник Markdown. Пустую строку рисовать не надо — решает вызывающий. */
  text: string;
  className?: string;
}

/**
 * Показ исходника Markdown из базы — то, что бэкенд отдаёт полем `text`
 * редактируемых разделов.
 *
 * ### Почему здесь нет `rehype-raw`
 *
 * Это единственная граница, на которой отсекается чужой исполняемый код,
 * и она проходит здесь, а не на бэкенде — в отличие от `content` новости,
 * который чистит jsoup (разбор — в `pages/NewsDetailPage/ui/NewsArticle.tsx`).
 * `text` бэкенд не санитизирует **вовсе**, и это осознанное решение
 * контракта: санитайзер работает с HTML, а применённый к исходнику Markdown
 * он экранирует служебные символы и портит разметку, которую модератор
 * увидит в форме при следующей правке.
 *
 * Значит, гарантию даёт шаг рендера. `react-markdown` по умолчанию сырой HTML
 * внутри Markdown не исполняет, а выводит текстом; `rehype-raw` включает его
 * обратно — вместе с XSS. Пакет не установлен и ставиться не должен:
 * docs/API.md предупреждает об этом отдельным абзацем, а FRONTEND_BACKLOG —
 * прямо в тикете F-17.
 *
 * Второе следствие того же: `dangerouslySetInnerHTML` для `text` неприменим.
 *
 * ### Почему `remark-gfm`
 *
 * Ради паритета с оригиналом, а не ради фич. Старый портал рендерил
 * `ngx-markdown` поверх `marked`, у которого GFM включён по умолчанию,
 * и в тулбаре его редактора были кнопки «Таблица» и «Чекбокс». То есть
 * в перенесённых текстах таблицы, зачёркивание и списки задач встретятся,
 * и без расширения модератор увидел бы на месте своей таблицы строку
 * с палками.
 *
 * ### Ссылки
 *
 * Адреса `react-markdown` фильтрует сам — `javascript:` и прочие опасные
 * схемы отбрасывает встроенный `defaultUrlTransform`, отдельной проверки
 * здесь нет намеренно, второй такой список стал бы вторым источником правды.
 */
export default function Markdown({ text, className }: MarkdownProps) {
  return (
    // prose из @tailwindcss/typography: у разметки, собранной из Markdown,
    // своих классов нет, а сброс Tailwind снимает стили с h2, ul и blockquote
    // — без него раздел выглядит одним сплошным абзацем. Набор модификаторов
    // тот же, что у статьи новости: два способа показа текста на портале
    // должны давать одну типографику.
    // max-w-none: ширину держит карточка, а не типографика.
    <div
      className={cn(
        'prose prose-sm max-w-none prose-headings:text-text-heading prose-a:text-primary prose-img:rounded',
        // Длинное неразрывное слово — обычно вставленный адрес — иначе
        // распирает страницу ровно так же, как широкая таблица ниже.
        'break-words',
        className,
      )}
    >
      <ReactMarkdown
        remarkPlugins={[remarkGfm]}
        components={{ a: MarkdownLink, table: MarkdownTable }}
      >
        {text}
      </ReactMarkdown>
    </div>
  );
}

/**
 * Ссылка внутри текста модератора.
 *
 * Внутренние уводятся в роутер: в тексте блоков лежат ссылки на разделы
 * портала (в оригинале карточки главной вели на `/about/fields-of-study`
 * и соседние), и обычный `<a>` на такой адрес перезагружает приложение
 * целиком — с потерей кэша Query и мельканием белого экрана.
 *
 * Внутренним считается адрес, начинающийся с одного слэша. Двойной —
 * это протоколонезависимый внешний (`//example.com`), и роутер увёл бы
 * по нему на несуществующий путь портала.
 *
 * Якорь (`#раздел`) остаётся обычной ссылкой: браузер и так прокрутит
 * к нужному месту, а `target` открыл бы соседнюю вкладку с той же страницей.
 *
 * Пустой адрес — это то, что осталось от опасной схемы: `defaultUrlTransform`
 * не выбрасывает такую ссылку, а обнуляет ей `href`. Якорь без адреса —
 * ловушка для клавиатуры: остановка табуляции, которая ничего не делает,
 * — поэтому от ссылки остаётся только её текст.
 *
 * Остальное — наружу, в новой вкладке и с `rel`, потому что адреса пишет
 * модератор, а `noopener` — единственное, что мешает открытой странице
 * дотянуться до нашей через `window.opener`.
 *
 * Пропсы перечислены поимённо, а не проброшены через `...rest`, и это
 * не придирка к стилю. `react-markdown` передаёт кастомному компоненту
 * ещё и разобранный узел mdast пропом `node`; в разметке он оседает
 * атрибутом `node="[object Object]"` — React не отсеивает его, потому что
 * имя в нижнем регистре и выглядит как обычный HTML-атрибут. Поймано
 * в браузере на живом блоке. У ссылки из Markdown осмысленных атрибутов
 * ровно два, `href` и `title` (последний — из `[текст](/url "подсказка")`),
 * и перечислить их короче, чем вычитать лишнее.
 */
const MarkdownLink: Components['a'] = ({ href, title, children }) => {
  if (!href) return <>{children}</>;

  if (href.startsWith('/') && !href.startsWith('//')) {
    return (
      <Link to={href} title={title}>
        {children}
      </Link>
    );
  }

  if (href.startsWith('#')) {
    return (
      <a href={href} title={title}>
        {children}
      </a>
    );
  }

  return (
    <a href={href} title={title} target="_blank" rel="noopener noreferrer">
      {children}
    </a>
  );
};

/**
 * Таблица в собственной прокрутке.
 *
 * Без обёртки широкая таблица распирает не себя, а **страницу целиком**:
 * измерено в браузере на семи колонках при ширине окна 390 px — документ
 * стал 639 px, и горизонтально поехали заодно шапка, меню, подвал и лента
 * новостей. Симптом выглядит как сломанная вёрстка портала, а причина
 * лежит в чужом тексте, который никто не проверял.
 *
 * Случай не надуманный: редактируемые разделы — это учебные планы и списки
 * дисциплин, то есть таблицы на пять-семь колонок здесь норма, а `text`
 * пишет модератор, у которого ни ревью, ни предпросмотра на телефоне нет.
 *
 * Прокрутка внутренняя, а не сжатие колонок: план занятий, ужатый до
 * нечитаемого, не лучше уехавшей вёрстки.
 */
const MarkdownTable: Components['table'] = ({ children }) => (
  <div className="overflow-x-auto">
    <table>{children}</table>
  </div>
);
