import { cn } from '@shared/lib';

import { richTextClass } from './richTextClass';

interface RichTextProps {
  /** Готовый HTML из базы. Пустую строку рисовать не надо — решает вызывающий. */
  html: string;
  className?: string;
}

/**
 * Показ rich-text полей: `content` новости, конференции и достижения,
 * `education` и `qualification` карточки ППС.
 *
 * ### Почему здесь `dangerouslySetInnerHTML`
 *
 * Это HTML из редактора, и другого способа показать его разметкой
 * не существует. Опасность у приёма ровно одна — чужой исполняемый код
 * в тексте, — и границей, на которой он отсекается, выбран **бэкенд**,
 * а не браузер:
 *
 * * все четыре сервиса прогоняют rich-text через общий `HtmlSanitizer`
 *   на каждом пути записи. Внутри `Jsoup.clean` по белому списку
 *   `Safelist.relaxed()`. Взят белый список, а не вырезание `<script>`:
 *   код прячется в атрибутах (`onerror`) и в схеме `javascript:` внутри
 *   `href`, поэтому перечень опасного неполон по определению,
 *   а перечень нужного — конечен;
 * * пустой после чистки текст бэкенд не сохраняет вовсе — `400` со словарём
 *   `errors`. То есть запись с пустым `content` в выдаче появиться не может;
 * * это покрыто интеграционными тестами бэкенда: скрипт при создании
 *   и при обновлении, `onerror` в теге без слова `script`, относительная
 *   картинка.
 *
 * Второй санитайзер на клиенте не ставится сознательно. Он стал бы вторым
 * источником правды о допустимых тегах, и в момент, когда его список
 * окажется строже jsoup'ового, у модератора молча пропадёт форматирование
 * — причём только у части читателей, что ловится месяцами.
 *
 * Условие, при котором решение перестаёт быть верным, ровно одно и записано
 * в ARCHITECTURE §7: перенос старой базы, где Quill-HTML никогда не чистился.
 * Дамп пойдёт в таблицу мимо сервисов, то есть мимо санитайзера. Импорт
 * обязан чистить сам; если этого не сделают — сюда придёт `dompurify`,
 * и это осознанный размен, а не забытая дыра.
 *
 * Для `text` редактируемых страниц приём **не годится**: там в базе лежит
 * исходник Markdown, который бэкенд не санитизирует вовсе, — его рендерит
 * `shared/ui/Markdown.tsx` без `rehype-raw` (docs/API.md).
 */
export function RichText({ html, className }: RichTextProps) {
  return (
    <div className={cn(richTextClass, className)} dangerouslySetInnerHTML={{ __html: html }} />
  );
}
