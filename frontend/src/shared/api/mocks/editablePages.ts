import { http, HttpResponse } from 'msw';

import type { EditablePage, EditablePageSlug } from '@shared/types';

/** `*` вместо origin — по той же причине, что и у новостей. */
const PUBLIC_PAGES = '*/api/public/pages/:slug';

/**
 * Редактируемые разделы. Текст задаётся по слагу, остальные приходят
 * **пустыми** — ровно так выглядит чистая база: ченджсет
 * `008-seed-editable-pages` заводит все тринадцать разделов с `text: ''`,
 * и никто их с тех пор не трогал.
 *
 * Умолчание выбрано не для удобства тестов, а потому, что это состояние,
 * в котором портал сегодня и разворачивается. Мок, отдающий выдуманный текст
 * по умолчанию, прятал бы главную без обоих блоков — то самое, что на стенде
 * видно первым.
 *
 * Ветки `404` здесь нет: набор слагов закрыт и выражен union'ом
 * (`EditablePageSlug`), из типизированного кода неизвестный слаг не уйдёт.
 * Тесту, которому нужен `404` от не доехавшей миграции, проще подставить
 * свой хендлер через `server.use(...)`, чем всем остальным — держать
 * недостижимую ветку.
 */
export function editablePageHandlers(texts: Partial<Record<EditablePageSlug, string>> = {}) {
  return [
    http.get(PUBLIC_PAGES, ({ params }) => {
      const slug = params.slug as EditablePageSlug;

      return HttpResponse.json<EditablePage>({
        slug,
        // Подпись для списка в админке, а не заголовок страницы: рисовать
        // её публичная страница не должна, и в моке она нужна только
        // для полноты DTO.
        title: slug,
        text: texts[slug] ?? '',
        // Даты константами, а не `new Date()`: плавающее значение делает
        // падение теста невоспроизводимым — то же правило, что
        // у `timestamp` в `problemResponse`.
        createdAt: '2026-08-01T10:15:30.123456+03:00',
        updatedAt: '2026-08-20T10:15:30.123456+03:00',
      });
    }),
  ];
}
