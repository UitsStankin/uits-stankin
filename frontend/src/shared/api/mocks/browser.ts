import { setupWorker } from 'msw/browser';

import { authHandlers } from './auth';
import { fileHandlers } from './files';
import { handlers } from './handlers';
import { makeProfile, profileHandlers } from './profile';

/**
 * Перехватчик запросов для браузера. Включается флагом `VITE_ENABLE_MOCKS`
 * в `main.tsx`, сам по себе не запускается.
 *
 * Нужен ровно для того, чего на живом бэкенде не воспроизвести: пустых
 * списков, пятисоток, медленных ответов, протухшего токена. Отклонения
 * заводятся в консоли поверх общего набора:
 *
 *   worker.use(http.get('*\/api/public/news', () => new Response(null, { status: 500 })))
 *
 * Воркер `public/mockServiceWorker.js` создан командой `msw init` и правится
 * только ею.
 *
 * К общему набору здесь добавлены вход и профиль — то, чего в наборе
 * тестов нет намеренно (профиль по умолчанию означал бы вошедшего
 * пользователя в каждом тесте страницы). В браузере всё наоборот: без
 * входа портал на моках заканчивается формой логина, и ни личный кабинет,
 * ни админку посмотреть нельзя. Пароль мок не проверяет — пускает любого,
 * кто ввёл логин.
 *
 * Файлы — тоже здесь, а не в общем наборе: загрузку зовут только формы
 * за входом, и тестам она нужна точечно, с новым счётчиком ключей
 * на каждый тест. В браузере же без неё аватар и картинка в редакторе
 * упирались бы в необработанный запрос, а `/media` отдаёт загруженное
 * обратно — разбор в `files.ts`.
 *
 * Роль — модератор и преподаватель сразу: под первой открыт весь раздел
 * админки, кроме учётных записей (F-46), вторая добавляет в личный кабинет
 * карточку ППС — единственное место портала, где до админки можно
 * посмотреть форму с rich-text редактором (F-41). Совмещение не выдумано:
 * модератор кафедры — обычно преподаватель. Нужна другая роль —
 * `worker.use(...profileHandlers(makeProfile({ superuser: true })))`
 * в консоли браузера.
 */
export const worker = setupWorker(
  ...handlers,
  ...authHandlers(),
  ...profileHandlers(makeProfile({ moderator: true, teacher: true })),
  ...fileHandlers(),
);
