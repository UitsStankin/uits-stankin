/**
 * Увести фокус в область содержимого страницы, когда вернуть его некуда.
 *
 * Так заканчиваются два случая, и оба — про исчезнувший элемент:
 * модальное окно закрылось, а кнопки, которая его открыла, в документе
 * уже нет (`Modal/model/useModalBehavior.ts`); таблица с удалённой
 * строкой пропала вся, потому что строка была последней
 * (`DataTable/model/useRowFocusRescue.ts`). `focus()` на оторванном
 * от документа элементе молча ничего не делает, и человек с клавиатурой
 * остаётся на `body` — то есть в начале страницы.
 *
 * `main` — потому что это единственный элемент, который есть на любой
 * странице портала и стоит там же, где шла работа: от него до кнопок
 * раздела один-два Tab, а диктор объявляет область содержимого.
 *
 * `tabindex` снимается по потере фокуса: оставленный насовсем, он сделал
 * бы половину страницы одной большой остановкой табуляции.
 */
export function focusPageContent(): void {
  const content = document.querySelector('main');

  if (!(content instanceof HTMLElement)) return;

  content.tabIndex = -1;
  content.focus();
  content.addEventListener('blur', () => content.removeAttribute('tabindex'), { once: true });
}
