/**
 * Поисковый запрос в адресе: разбор.
 *
 * Живёт рядом с номером страницы (`pageParam.ts`) и порядком сортировки
 * (`sortParam.ts`) по той же причине: запрос — часть адреса списка,
 * а не состояние компонента. Ссылку на «аспирантов Чеканина» можно
 * переслать, открыть в новой вкладке и вернуться на неё кнопкой «назад»;
 * `useState` теряет всё это.
 *
 * Имя параметра — контрактное (`?q=`, docs/API.md), то есть в адресе
 * и в запросе лежит побайтово одно и то же, и переводить одно в другое
 * не нужно. Сборкой адреса занимается `pageHref`: запрос обязан пережить
 * перелистывание, а страница — смену запроса, и оба правила стоят там.
 */

/** Имя query-параметра с поисковым запросом. Знают двое: разбор и сборка. */
export const SEARCH_PARAM = 'q';

/**
 * Запрос из адреса. Пустая строка означает «поиска нет».
 *
 * Пробельный запрос приравнен к пустому — тем же правилом, что и на
 * бэкенде (`SearchText.normalize`), и это не косметика: `?q=%20%20`
 * дало бы отдельный ключ кэша и лишний запрос за тем же самым списком,
 * а показал бы он, вопреки надписи над таблицей, всех.
 *
 * Обрезка по краям — только у значения, уходящего в запрос. То, что
 * человек набрал в поле, остаётся как набрано: съеденный пробел между
 * словами под курсором выглядит поломкой поля ввода.
 */
export function parseSearch(raw: string | null): string {
  return raw === null ? '' : raw.trim();
}
