/**
 * Форма существительного при числительном по-русски: 1 секунду,
 * 2 секунды, 5 секунд.
 *
 * Форм три, и правило не сводится к «одна или много», как в английском:
 * выбор зависит от последней цифры, а второй десяток из него выпадает
 * целиком — 11, 12, 14 идут с той же формой, что и 25.
 *
 * Возвращается одно слово, без числа: падеж и предлог вокруг него
 * у каждой фразы свои («через 42 секунды», «осталось 42 секунды»),
 * и склеивать их здесь значило бы вносить в утилиту чужой текст.
 *
 * @param forms — формы для 1, для 2–4 и для 5–20: `['секунду', 'секунды', 'секунд']`
 */
export function pluralize(count: number, forms: readonly [string, string, string]): string {
  const hundreds = Math.abs(count) % 100;
  if (hundreds > 10 && hundreds < 20) return forms[2];

  const units = hundreds % 10;
  if (units === 1) return forms[0];
  if (units > 1 && units < 5) return forms[1];

  return forms[2];
}
