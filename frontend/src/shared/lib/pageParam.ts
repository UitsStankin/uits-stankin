/**
 * Номер страницы в адресе: разбор и сборка.
 *
 * **В адресе счёт с единицы, в запросе — с нуля.** Пользователю показывается
 * человеческая нумерация (`?page=0` выглядит поломкой), контракту нужна
 * спринговая (`shared/types/api.types.ts`). Пересчёт делает модель списка,
 * а вот разбор адреса и сборка ссылок живут здесь — это то самое место,
 * где список молча съезжает на одну страницу, если развести его по файлам.
 *
 * Вынесено из ленты новостей, когда списочных страниц стало две: у ППС
 * (F-21), УВП, конференций и достижений пагинация одна и та же, и второй
 * копией этих двадцати строк разошлись бы правила — «мусор в адресе»
 * и «первая страница без параметра» договорены один раз на портал.
 */

/** Имя query-параметра со страницей. Знают двое: разбор и сборка адреса. */
export const PAGE_PARAM = 'page';

/**
 * Номер страницы из адреса. Всё, что не похоже на номер, — первая страница.
 *
 * `?page=abc`, `?page=-1`, `?page=2.5` приходят от людей, правящих адрес
 * руками, и от чужих ссылок. Отвечать на это ошибкой незачем: показать
 * первую страницу — ровно то, чего от списка ждут.
 *
 * Про границы данных здесь не знают: `totalPages` известен только после
 * ответа, и «такой страницы нет» — решение модели, а не разбора адреса.
 */
export function parsePage(raw: string | null): number {
  const parsed = Number(raw);
  return Number.isInteger(parsed) && parsed >= 1 ? parsed : 1;
}

/**
 * Адрес списка с нужной страницей.
 *
 * `extra` — остальные параметры адреса, которые обязаны пережить
 * перелистывание: порядок сортировки в админке, а дальше и фильтры.
 * Без них ссылка «страница 2» сбрасывала бы порядок к умолчанию,
 * и список менялся бы на ровном месте. `null` в значении означает
 * «параметра нет» — так умолчание не попадает в адрес.
 */
export function pageHref(
  route: string,
  page: number,
  extra: Record<string, string | null> = {},
): string {
  const params = new URLSearchParams();

  // Первая страница — без параметра: `?page=1` в адресе ничего не добавляет,
  // зато раздваивает канонический адрес списка на два разных.
  if (page > 1) params.set(PAGE_PARAM, String(page));

  for (const [name, value] of Object.entries(extra)) {
    if (value !== null) params.set(name, value);
  }

  const query = params.toString();
  if (query === '') return route;

  // Запятая в значении сортировки (`name,desc`) экранируется в `%2C`,
  // хотя по RFC 3986 она в query разрешена. Возвращаем её на место:
  // адрес списка человек видит в строке браузера и пересылает коллеге,
  // а `%2C` в нём выглядит поломкой.
  return `${route}?${query.replace(/%2C/g, ',')}`;
}
