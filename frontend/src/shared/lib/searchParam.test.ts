import { describe, expect, it } from 'vitest';

import { parseSearch } from './searchParam';

/**
 * Поисковый запрос из адреса. Сюда приезжает не только то, что фронт
 * написал сам: адрес правят руками, присылают ссылками и режут
 * при копировании.
 */
describe('parseSearch', () => {
  it('берёт запрос, когда он есть', () => {
    expect(parseSearch('чеканин')).toBe('чеканин');
    expect(parseSearch('абрамов пётр')).toBe('абрамов пётр');
  });

  it('без параметра поиска нет', () => {
    expect(parseSearch(null)).toBe('');
    expect(parseSearch('')).toBe('');
  });

  /**
   * Пробельный запрос равен пустому — тем же правилом, что и на бэкенде
   * (`SearchText.normalize`). Иначе `?q=%20` дал бы отдельный ключ кэша
   * и лишний запрос за тем же самым списком, а надпись «найдено» встала бы
   * над полным списком.
   */
  it('пробельный запрос — это отсутствие поиска', () => {
    expect(parseSearch('   ')).toBe('');
    expect(parseSearch('\n\t')).toBe('');
  });

  /** Пробелы по краям срезаются, внутри — остаются: это разделитель слов. */
  it('обрезает края, но не середину', () => {
    expect(parseSearch('  чеканин  ')).toBe('чеканин');
    expect(parseSearch(' абрамов  пётр ')).toBe('абрамов  пётр');
  });

  /**
   * `%` и `_` — обычные символы: бэкенд экранирует их перед `like`
   * (`SearchText.escapeLike`), и обрезать их здесь значило бы чинить
   * то, что не сломано.
   */
  it('не трогает символы шаблона', () => {
    expect(parseSearch('100%')).toBe('100%');
    expect(parseSearch('a_b')).toBe('a_b');
  });
});
