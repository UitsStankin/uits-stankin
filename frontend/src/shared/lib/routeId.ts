/**
 * Идентификатор записи из адреса.
 *
 * Всё, что не положительное целое, — `null`: `/about/news/abc`,
 * `/about/employee/teachers/-1`, `1.5`. Такой адрес в запрос уходить
 * не должен вовсе — `@PathVariable Long` на бэкенде отвечает на «abc»
 * четырёхсотой, и человек увидел бы «ошибка сервера» там, где на самом деле
 * опечатка в ссылке. Для него это несуществующая страница, и показать надо
 * её же.
 *
 * Ноль отличается от `parsePage`: страницы считаются с единицы, и `id` тоже.
 *
 * Вынесено из детальной новости, когда таких страниц стало две: правило
 * у них общее, а его тонкость — ровно в том, что `Number('')` и
 * `Number(null)` дают ноль, — и разъехавшиеся копии молча пропустили бы
 * пустой адрес в запрос.
 */
export function parseId(raw: string | undefined): number | null {
  const parsed = Number(raw);
  return Number.isInteger(parsed) && parsed > 0 ? parsed : null;
}
