import type { LucideIcon } from 'lucide-react';

/**
 * Пункт бокового меню.
 *
 * Структура рекурсивная и в текущем меню доходит до трёх уровней:
 * «Учебная деятельность» → «Бакалавриат» → «Учебные планы».
 *
 * Группа от ссылки отличается наличием `children`, отдельного признака
 * для этого не нужно: у групп в старом конфиге были пути вроде `/about`,
 * но страниц по ним не существовало — они только раскрывались.
 */
export interface NavItem {
  /** Стабильный идентификатор: ключ для React и для подсветки активного пункта. */
  key: string;

  /** Подпись в меню. */
  title: string;

  /** Компонент иконки из lucide-react. */
  icon?: LucideIcon;

  /** Путь роутера. У групп отсутствует — по ним нет страниц. */
  path?: string;

  /** Вложенные пункты. Наличие делает пункт группой. */
  children?: readonly NavItem[];
}
