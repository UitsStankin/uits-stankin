/**
 * Достижения кафедры — по контракту T-29 (docs/API.md, «Достижения
 * кафедры»): награды, гранты и победы в конкурсах.
 *
 * В оригинале это была пара классов `ListAchievement` и `Achievement`
 * в `planned.types.ts`: список без тела записи, деталь — с телом. Модуль
 * появился на бэкенде, тип сверен со Swagger и переехал сюда по правилу
 * из шапки того файла. Пара при этом схлопнулась в один тип: обе ручки
 * отдают **один и тот же DTO**, то есть `content` приезжает уже в списке —
 * как у новостей и конференций.
 *
 * Против старой модели изменились три вещи, все — решением контракта:
 * `isPublished` стал `display` (соглашение о видимости одно на все
 * сущности), `image` — парой `previewImage` / `previewImageUrl`,
 * а строка `teacher` с готовым именем и отдельный `teacherId` —
 * парой `teacherId` / `teacherName`.
 */

import type { Page } from './api.types';

/**
 * Достижение — ответ `GET /api/(public/)achievements[/{id}]`
 * и `GET /api/public/teachers/{teacherId}/achievements`.
 *
 * Необязательных полей здесь ровно одно — пара `teacherId` / `teacherName`;
 * всё остальное обязательно и приходит заполненным (docs/API.md,
 * «Достижения кафедры»). Это отличает достижение от конференции, где
 * необязательно почти всё, и позволяет карточке не проверять каждый блок
 * на пустоту.
 */
export type Achievement = {
  id: number;
  title: string;
  /** Краткое описание для карточки в списке. Плоский текст, не разметка. */
  description: string;
  /**
   * Rich-text, HTML — единственное такое поле достижения; `title`
   * и `description` плоские и выводятся текстовым узлом.
   *
   * Обязательно, в отличие от конференции: тело, вычищенное санитайзером
   * до пустоты, — это `400` на сохранении, а не запись с пустым
   * содержанием. Поэтому здесь `string`, а не `string | null`.
   */
  content: string;
  /**
   * Ключ файла обложки в хранилище. Уходит обратно при сохранении,
   * для показа не годится — для этого есть `previewImageUrl`.
   */
  previewImage: string;
  /** Готовый адрес обложки для `<img src>`, относительный. */
  previewImageUrl: string;
  /** ISO-8601 со смещением. */
  createdAt: string;
  /**
   * Опубликовано ли. В публичной выдаче всегда `true` — скрытые достижения
   * оттуда не приходят вовсе, и по прямой ссылке дают `404`, а не `403`.
   * Поле нужно админскому списку, чтобы отличать черновики.
   */
  display: boolean;
  /**
   * Карточка ППС, к которой привязано достижение, — или `null`
   * у кафедрального.
   *
   * `null` приходит и после удаления карточки: достижение переживает
   * преподавателя, теряя привязку. Поэтому пара всегда проверяется целиком,
   * а не «раз есть имя, значит есть и ссылка».
   */
  teacherId: number | null;
  /**
   * Имя преподавателя, собранное сервером из фамилии, имени и отчества
   * карточки: отдельный запрос за преподавателем ради подписи не нужен.
   */
  teacherName: string | null;
};

/**
 * Тело `POST /api/achievements` и `PUT /api/achievements/{id}` — те же поля
 * без `id`, `createdAt`, `previewImageUrl` и `teacherName`.
 *
 * `PUT` — полная замена. Необязателен только `teacherId`, и «не привязано»
 * выражается через `null`; обложку снять правкой нельзя — `PUT` без
 * `previewImage` это `400`, а не достижение без картинки. Лимиты:
 * `title` — 100 символов, ключ обложки — 100; `description` и `content`
 * не ограничены. Ссылка на несуществующую карточку ППС и ключ
 * несуществующего файла — `400`.
 */
export type AchievementRequest = {
  title: string;
  description: string;
  content: string;
  /** Ключ файла из `POST /api/files` с категорией `achievements`, не адрес. */
  previewImage: string;
  display: boolean;
  teacherId: number | null;
};

/** Страница достижений — то, что отдают списочные ручки. Новые сверху. */
export type AchievementPage = Page<Achievement>;
