/**
 * Аспирантура — контракт T-49 (docs/API.md, «Аспирантура»).
 *
 * Модуль на бэкенде называется `students` и закрывает сразу два пункта
 * матрицы паритета: 14 (аспирантура) и 13 (студенты). Собственных ручек
 * у студента нет вовсе — человек заводится вместе с записью аспирантуры
 * и удаляется вместе с ней, — поэтому и типа `Student` здесь нет:
 * наружу студент отдаётся только в составе записи.
 *
 * Тип пришёл на смену `GraduateStudent` из `planned.types.ts`, где лежала
 * форма старого Django-ответа (`student.full_name`, `teacher.full_name`
 * вложенными объектами). Правило того файла — сверить со Swagger
 * и переехать, когда модуль появится на бэкенде, — и это ровно тот случай.
 * Совпадения почти нет: Spring отдаёт запись плоской, ФИО склеенными
 * строками, а идентификаторы — отдельными полями.
 */

import type { Page, PageParams } from './api.types';

/**
 * Запись аспирантуры — элемент `GET /api/public/postgraduates`.
 *
 * Одна запись — это связка «аспирант ↔ руководитель», а не карточка
 * человека: `id` принадлежит записи, `studentId` — студенту, `teacherId` —
 * карточке ППС. Последний годится для `teacherRoute`: это тот же
 * идентификатор, что у публичной карточки преподавателя.
 */
export type Postgraduate = {
  /** Идентификатор записи аспирантуры. Ни студент, ни преподаватель. */
  id: number;
  studentId: number;
  /**
   * «Фамилия Имя Отчество» одной строкой — склеивает бэкенд, той же
   * схемой, что и в расписаниях. Ходить за списком ППС ради подписи
   * не нужно, но и разобрать строку обратно на части нельзя.
   */
  studentName: string;
  /**
   * Шифр научной специальности («2.3.1»). Колонка `speciality`
   * объявлена без `nullable = false`, а пустая строка на записи
   * превращается в `null` общей нормализацией тела («Базовое»
   * в docs/API.md) — значит, незаполненная приходит именно `null`.
   * В docs/API.md это не оговорено, форма поля взята из схемы БД.
   */
  speciality: string | null;
  /** Тема диссертации. Нулевая по той же причине, что и специальность. */
  diplomaTheme: string | null;
  /** Год поступления. Обязателен и не раньше 2000 — проверяет бэкенд. */
  admissionYear: number;
  /**
   * Научный руководитель. Незаполненный приходит `null` **в обоих полях**
   * сразу, а не строкой-заглушкой: «подпись „не назначен“ рисует
   * интерфейс» (docs/API.md, «Аспирантура»). Пара `null` возникает
   * не только у новых записей — удаление карточки ППС обнуляет
   * руководителя у его аспирантов, как у достижений кафедры.
   */
  teacherId: number | null;
  teacherName: string | null;
};

/** Страница записей — ответ `GET /api/public/postgraduates`. */
export type PostgraduatePage = Page<Postgraduate>;

/**
 * Параметры списка: страница плюс поиск.
 *
 * `q` появился с T-78 по заявке B-3 — до него список читался только
 * алфавитом и постранично. Поиск по подстроке идёт сразу по всем колонкам
 * таблицы: ФИО аспиранта, тема, специальность, год поступления и ФИО
 * руководителя. Значения склеиваются на сервере в одну строку через пробел,
 * поэтому `абрамов пётр` находит запись, хотя ни в одном отдельном поле
 * такого текста нет (docs/API.md, «Аспирантура»).
 *
 * Фильтров `?teacherId=` и `?speciality=` здесь по-прежнему нет, хотя
 * контракт их принимает: потребителя у них не появилось. Правило то же,
 * по которому `q` не заводили заранее, — параметр без потребителя
 * проверить нечем.
 */
export type PostgraduateListParams = PageParams & {
  /**
   * Пустое значение равносильно отсутствию фильтра, и на бэкенде тоже
   * (`SearchText.normalize`). Но отправлять `q: ''` всё равно не следует:
   * это второй ключ кэша и второй запрос за тем же самым списком —
   * пустой запрос выбрасывает модель, а не сервер.
   */
  q?: string;
};

/**
 * Уровень образования студента — код закрытого словаря, подписи рисует
 * фронт (docs/API.md, «Аспирантура»). В записи аспирантуры допустим
 * только `POSTGRADUATE`: остальное сервер отвергает `400` и при создании,
 * и при правке. Весь словарь всё равно описан — так он приходит в ответе,
 * и запись, заведённая мимо портала, не должна ломать тип.
 */
export type EducationLevel = 'BACHELOR' | 'MASTER' | 'POSTGRADUATE' | 'SPECIALIST';

/**
 * Студент в составе записи аспирантуры — так он уходит в теле запроса
 * и так же приходит в ответе `GET /api/postgraduates/{id}`.
 *
 * Своих ручек у студента нет: он заводится вместе с записью и удаляется
 * вместе с ней. Группа живёт только здесь — в публичный список она
 * не уходила и на старом портале.
 */
export type PostgraduateStudent = {
  lastName: string;
  firstName: string;
  patronymic: string | null;
  group: string;
  educationLevel: EducationLevel;
  speciality: string | null;
  diplomaTheme: string | null;
  admissionYear: number;
};

/**
 * Запись аспирантуры в составе полей формы — ответ модераторской ручки
 * `GET /api/postgraduates/{id}`. Ровно то, что принимает `PUT`, плюс `id`.
 *
 * `student` объявлен нулевым, хотя docs/API.md всегда показывает объект:
 * колонка `student_id` в схеме необязательна — наследство Django, где
 * удаление студента обнуляло ссылку (`on_delete=SET_NULL`), — и маппер
 * бэкенда в этом случае отдаёт `null`. Форма такую запись открывает
 * пустой, а сохранение заводит ей студента заново (`updatePostgraduate`).
 */
export type PostgraduateDetails = {
  id: number;
  student: PostgraduateStudent | null;
  teacherId: number | null;
};

/**
 * Тело `POST` и `PUT /api/postgraduates` — одно на оба. `PUT` — полная
 * замена: поле, не пришедшее в теле, обнуляется. Руководитель —
 * идентификатором карточки ППС, `null` — «не назначен».
 */
export type PostgraduateRequest = {
  student: PostgraduateStudent;
  teacherId: number | null;
};
