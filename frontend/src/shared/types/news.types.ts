/**
 * Новости и объявления кафедры — `NewsResponseDto` / `NewsRequestDto`.
 *
 * В оригинале это были классы `ListPost` и `Post` с конструкторами,
 * переводившими snake_case в camelCase. Ни того, ни другого больше не нужно:
 * Spring отдаёт camelCase сам, а инстансы классов ломают structural sharing
 * в TanStack Query — после каждого перезапроса `new Post(...)` возвращает
 * новую ссылку, и подписанные компоненты перерисовываются, даже когда данные
 * не изменились.
 *
 * Разделения «список — деталь» тоже нет: обе ручки отдают один и тот же DTO,
 * то есть `content` новости приезжает уже в списке.
 */

import type { Page } from './api.types';

/**
 * Раздел, в котором показывается запись. Одна сущность на два раздела —
 * так же, как `posts-base.service.ts` в оригинале обслуживал и новости,
 * и объявления.
 */
export type PostType = 'news' | 'announcements';

/** Новость или объявление — ответ `GET /api/(public/)news[/{id}]`. */
export type News = {
  id: number;
  title: string;
  /** Анонс для карточки в списке; необязателен при создании. */
  shortDescription: string | null;
  postType: PostType;
  /**
   * Ключ файла обложки в хранилище. Уходит обратно при сохранении,
   * для показа не годится — для этого есть `previewImageUrl`.
   */
  previewImage: string | null;
  /** Готовый адрес обложки для `<img src>`, относительный. */
  previewImageUrl: string | null;
  /** Текст для `alt` обложки. */
  previewImageDescription: string | null;
  /** Rich-text, HTML. */
  content: string;
  /** ISO-8601 со смещением: `2026-07-24T10:15:30.123456+04:00`. */
  createdAt: string;
  /**
   * Опубликована ли. В публичной выдаче всегда `true` — скрытые записи
   * оттуда не приходят вовсе, и по прямой ссылке дают `404`, а не `403`.
   * Поле нужно админскому списку, чтобы отличать черновики.
   */
  display: boolean;
  /**
   * «Имя Фамилия» автора, склеенные бэкендом. Автор у записи есть всегда,
   * но строка бывает **пустой** — если у него не заполнены ни имя,
   * ни фамилия. Показывать через запасной вариант, а не как есть.
   */
  authorName: string;
};

/**
 * Тело `POST /api/news` и `PUT /api/news/{id}`.
 *
 * `PUT` — полная замена, а не частичное обновление: не пришедшее в теле поле
 * обнуляется. Форма редактирования обязана отправлять все поля, включая
 * незатронутые, — поэтому здесь нет необязательных полей, а «не задано»
 * выражается через `null`.
 *
 * Обложка отправляется **ключом** (`previewImage`) из ответа `POST /api/files`;
 * ключ проверяется бэкендом, и на несуществующий файл приходит `400`.
 */
export type NewsRequest = {
  /** От 5 до 100 символов. */
  title: string;
  /** До 255 символов. */
  shortDescription: string | null;
  postType: PostType;
  /** Ключ файла, не адрес. До 100 символов. */
  previewImage: string | null;
  /** До 256 символов. */
  previewImageDescription: string | null;
  content: string;
  display: boolean;
};

/** Страница новостей — то, что отдают списочные ручки. */
export type NewsPage = Page<News>;
