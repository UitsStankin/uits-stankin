/**
 * Редактируемые разделы сайта — `EditablePageResponseDto`.
 *
 * Тринадцать текстовых блоков, содержимое которых правит модератор: контакты,
 * нормативные документы, учебные планы, два блока главной. Никакой логики,
 * кроме хранения текста, за ними нет (docs/API.md, «Редактируемые страницы»).
 */

/**
 * Слаг раздела — короткий латинский идентификатор в пути (`contacts`, а не `7`).
 *
 * Union из тринадцати литералов, а не `string`, потому что **набор закрыт**:
 * слаги создаются миграцией при первом запуске, а создать четырнадцатый
 * или удалить существующий через API нельзя вовсе. Контракт объясняет
 * и почему: слаг захардкожен в маршрутах фронтенда, и удаление раздела
 * означало бы неустранимую дырку в навигации.
 *
 * Практическая польза ровно одна, зато ежедневная: опечатка в слаге —
 * ошибка компиляции, а не молчаливый `404` на живой странице. Слаг
 * приходит не из данных, его пишет разработчик в коде страницы, поэтому
 * проверить его типом можно и нужно.
 *
 * Последние два — не страницы: собственного адреса у них нет,
 * они выводятся на главной над и под лентой новостей.
 */
export type EditablePageSlug =
  | 'fields-of-study'
  | 'contacts'
  | 'documents-department'
  | 'documents-university'
  | 'bachelor-edu-plans'
  | 'bachelor-graduate'
  | 'bachelor-practices'
  | 'master-edu-plans'
  | 'master-graduate'
  | 'master-practices'
  | 'scientific-activity-postgraduate'
  | 'home-before'
  | 'home-after';

/** Раздел — ответ `GET /api/public/pages/{slug}`. */
export type EditablePage = {
  slug: EditablePageSlug;
  /**
   * Подпись раздела **для списка в админ-панели**, а не заголовок публичной
   * страницы: на старом портале заголовок рисовала навигация, и это
   * поведение сохраняется. Рисовать `title` над текстом не нужно.
   *
   * `null` приходит в строках, перенесённых со старого портала, где поле
   * заполнено не везде. На запись оно обязательно — форма правки (F-23,
   * блок 4) требует непустую подпись.
   */
  title: string | null;
  /**
   * **Исходник Markdown, а не HTML** — единственное отличие от `content`
   * новости, где в базе лежит готовый HTML из редактора.
   *
   * Отсюда следует способ показа, и он не на выбор: `react-markdown`
   * **без** `rehype-raw`. Бэкенд `text` не санитизирует вовсе — санитайзер
   * работает с HTML и, применённый к исходнику Markdown, экранировал бы
   * служебные символы и портил разметку, которую модератор увидит в форме
   * при следующей правке. Гарантия «браузер не исполнит чужой HTML»
   * держится на шаге рендера, то есть на `shared/ui/Markdown`.
   * `dangerouslySetInnerHTML` неприменим по той же причине.
   *
   * Не `string | null`: колонка объявлена `nullable = false`. Пустая строка —
   * легальное значение и означает «модератор ещё не заполнил»: раздел нельзя
   * удалить, но можно опустошить, и `PUT` с `text: ""` делает именно это.
   * Это единственное поле, на которое не действует правило контракта
   * «пустая строка = `null`».
   */
  text: string;
  /** ISO-8601 со смещением. */
  createdAt: string;
  updatedAt: string;
};
