/**
 * Общие формы транспорта, не привязанные ни к одной сущности: страница
 * списка, её параметры и ответ загрузчика файлов.
 *
 * Источник — docs/API.md, разделы «Пагинация списков» и «Загрузка файлов».
 */

/**
 * Страница списка. Списочные ручки отдают не массив, а объект-страницу
 * (`PageResponseDto` на бэкенде) — распаковывать её должен вызывающий код,
 * а не api-клиент: `totalElements` и `totalPages` нужны пагинатору.
 *
 * `page` считается **с нуля**: первая страница — `page=0`. Django-пагинатор
 * в оригинале считал с единицы, и это ровно то место, где при переносе
 * страница будет молча съезжать на одну.
 *
 * Запрос страницы за пределами данных — не ошибка: приходит `200`
 * с пустым `content`.
 */
export type Page<T> = {
  /** Элементы текущей страницы. */
  content: readonly T[];
  /** Номер текущей страницы, счёт с нуля. */
  page: number;
  /** Запрошенный размер страницы, не фактическое число элементов в `content`. */
  size: number;
  /** Сколько элементов всего с учётом фильтров. */
  totalElements: number;
  /** Сколько всего страниц при текущем `size`. */
  totalPages: number;
};

/**
 * Query-параметры списочной ручки. Все необязательны: без них бэкенд отдаёт
 * первую страницу по 20 элементов со своей сортировкой по умолчанию
 * (новости — новые сверху, преподаватели — по алфавиту фамилий).
 */
export type PageParams = {
  /** Счёт с нуля: `page: 2` — третья страница. */
  page?: number;
  size?: number;
  /**
   * Поле и направление одной строкой: `'title,asc'`. Поле — только из схемы
   * ответа, на неизвестное приходит `400` с именем поля в `detail`.
   *
   * Сортировка сразу по нескольким полям делается повторением параметра
   * (`sort=a,asc&sort=b,desc`), а это уже свой сериализатор параметров:
   * axios из массива соберёт `sort[]=`, чего Spring не поймёт. Понадобится —
   * заведём тогда же, когда появится первый список с такой сортировкой.
   */
  sort?: string;
};

/**
 * Раздел хранилища, в который кладётся файл. По умолчанию `news`.
 *
 * Раздел решает и права, и применимость ключа: `avatars` открыт любому
 * авторизованному, остальные — админу и модератору, а ключ принимается
 * только полем своего раздела (docs/API.md, «Загрузка файлов»).
 */
export type FileCategory = 'news' | 'avatars' | 'publications' | 'achievements';

/**
 * Ответ `POST /api/files`.
 *
 * Два поля не дублируют друг друга: `key` уходит обратно на бэкенд
 * (например, в `previewImage` новости) и хранится в базе, `url` идёт
 * в `<img src>`. Собирать адрес из ключа на фронте нельзя — правило сборки
 * принадлежит бэкенду и изменится при переезде на объектное хранилище.
 */
export type FileUploadResponse = {
  key: string;
  url: string;
};
