import defaultAvatar from '@shared/assets/avatars/default-user.png';

/**
 * Аватар, когда пользователь свой не загрузил.
 *
 * Такой пользователь — обычное дело, а не переходное состояние: аватар
 * необязателен, и `avatar` с `avatarUrl` приходят из контракта как `null`.
 * Пустой `src` дал бы битую картинку, поэтому заглушка нужна каждому месту,
 * где показывают пользователя: меню профиля в шапке, карточке личного
 * кабинета, карточке ППС и предпросмотру в обеих формах правки.
 *
 * Прежде здесь стояло, что записать аватар некуда вовсе. Это перестало быть
 * правдой с T-26 и T-33: своё фото ставят и преподаватель в карточке ППС
 * (F-16), и любой пользователь в профиле (F-27) — через `POST /api/files`
 * с разделом `avatars`.
 *
 * Отдельный модуль, а не импорт картинки в каждом из них: место одно,
 * и заглушку меняют здесь. Адрес — импорт, а не строка: файл идёт через
 * сборщик и получает хеш в имени (D-F16), а переименованный или удалённый
 * файл ломает сборку, а не картинку у посетителя.
 */
export const DEFAULT_AVATAR_URL: string = defaultAvatar;
