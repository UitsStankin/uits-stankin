export const HELPERS_ROUTE = '/about/employee/uvp';

/**
 * Админка. Собственный раздел портала, а не отдельное приложение:
 * в оригинале по этому адресу жила админка Django, и совпадение пути
 * экономит строку в карте редиректов nginx при переезде — как
 * и у `/corp/personal`.
 *
 * Знают трое: список роутов, меню профиля в шапке и меню самого раздела
 * (`shared/config/adminNavigation.ts`), которое строит из него адреса
 * подразделов.
 */
export const ADMIN_ROUTE = '/admin';

/**
 * Дисциплины в админке — первый готовый раздел (F-40). Знают двое:
 * список разделов (`adminNavigation.ts`) и сама страница, собирающая
 * адреса пагинатора и сортировки.
 */
export const ADMIN_SUBJECTS_ROUTE = `${ADMIN_ROUTE}/subjects`;

/**
 * Новости и объявления в админке (F-43). Знают двое: список разделов
 * и сама страница — она собирает адреса пагинатора, сортировки и фильтра
 * по типу записи.
 */
export const ADMIN_NEWS_ROUTE = `${ADMIN_ROUTE}/news`;

/**
 * Карточки ППС в админке (F-44). Знают трое: список разделов, сама
 * страница (собирает адреса пагинатора и сортировки) и её же форма —
 * та живёт отдельным адресом и возвращается сюда после сохранения.
 */
export const ADMIN_TEACHERS_ROUTE = `${ADMIN_ROUTE}/teachers`;

/**
 * Адрес формы карточки ППС: правка существующей или заведение новой.
 *
 * Своим адресом, а не окном-панелью, как у новостей и дисциплин, —
 * и причина в данных, а не во вкусе. Списочная ручка отдаёт **короткую**
 * карточку: ни контактов, ни стажей, ни дисциплин, ни ключа фото,
 * ни связи с учётной записью. Форме всё равно нужен свой запрос
 * (`GET /api/public/teachers/{id}`), а у запроса, который может не дойти,
 * должен быть адрес: перезагрузка возвращает на ту же карточку,
 * а не на пустой список. Восемнадцать полей и два редактора в панели
 * шириной 576 px — второй довод, но он бы один не перевесил.
 *
 * `new` вместо `id` — заведение новой. Спутать их нельзя: `parseId`
 * не пропускает ничего, кроме положительного целого.
 */
export function adminTeacherRoute(id: number | 'new'): string {
  return `${ADMIN_TEACHERS_ROUTE}/${id}`;
}

/**
 * Учебно-вспомогательный персонал в админке (F-44). Знают двое: список
 * разделов и сама страница.
 *
 * Функции адреса формы, как у ППС, здесь нет: карточка УВП — четыре поля
 * и фото, и вся она целиком лежит в строке списка. Догружать нечего,
 * поэтому форма живёт окном-панелью, как у дисциплин, и своего адреса
 * у неё нет.
 */
export const ADMIN_HELPERS_ROUTE = `${ADMIN_ROUTE}/helpers`;
