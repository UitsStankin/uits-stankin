/**
 * Пути роутера, которые нужны не только самому роутеру.
 *
 * Путь логина знают четверо: список роутов, интерцептор axios (куда уводить
 * при протухшей сессии), защищённые роуты и сама форма входа. Строкой
 * в четырёх местах он обязательно разъедется при первом же переименовании.
 */
export const LOGIN_ROUTE = '/auth/login';

/**
 * Куда возвращать, когда конкретной страницы нет: после выхода и после входа
 * без запомненного адреса. Портал публичный, поэтому это главная, а не логин.
 */
export const HOME_ROUTE = '/';

/**
 * Личный кабинет. Адрес повторяет старый портал (`/corp/personal`), а не
 * `/cabinet` из ARCHITECTURE §5.4: на действующем сайте по этому пути живёт
 * та же страница, и совпадение избавляет от строки в карте редиректов nginx
 * при переезде.
 *
 * Знают двое: список роутов и меню профиля в шапке.
 */
export const PERSONAL_ROUTE = '/corp/personal';

/**
 * Лента новостей. Адрес взят из меню (`shared/config/navigation.ts`,
 * пункт `about/news`) и повторяет старый портал — как и `/corp/personal`,
 * это экономит строку в карте редиректов nginx при переезде.
 *
 * Знают трое: список роутов, сама страница (собирает адреса пагинатора)
 * и детальная (ссылка «ко всем новостям»).
 */
export const NEWS_ROUTE = '/about/news';

/**
 * Объявления кафедры. Тот же список записей, что и новости, — отличается
 * значением `postType` в запросе; раздел отдельный, потому что отдельным
 * пунктом меню он был и в старом портале.
 *
 * Знают трое: список роутов, страница раздела и главная — ссылка
 * «Все объявления» под секцией объявлений.
 */
export const ANNOUNCEMENTS_ROUTE = '/about/announcements';

/**
 * Адрес одной записи — и новости, и объявления. Функция, а не шаблон
 * по месту: адрес карточки собирают обе ленты и главная, а склейка строкой
 * в трёх местах разъезжается при первом же переименовании.
 *
 * Адрес один на оба раздела, хотя разделов два. Второй путь
 * (`/about/announcements/{id}`) означал бы два адреса у одной записи:
 * ручка `GET /api/public/news/{id}` не спрашивает про тип, ответ по обоим
 * адресам был бы побайтово одинаков, а поисковик получил бы дубль страницы.
 * Раздел, откуда пришли, восстанавливается по самой записи — на детальной
 * это ссылка «ко всем».
 */
export function newsItemRoute(id: number): string {
  return `${NEWS_ROUTE}/${id}`;
}

/**
 * Объявления о конференциях. Адрес взят из меню
 * (`shared/config/navigation.ts`, пункт `scientific-activities/conferences`)
 * и повторяет старый портал — как и остальные перенесённые разделы,
 * это экономит строку в карте редиректов nginx при переезде.
 *
 * Знают трое: список роутов, сама страница (собирает адреса пагинатора)
 * и детальная (ссылка «ко всем конференциям»).
 */
export const CONFERENCES_ROUTE = '/scientific-activities/conferences';

/**
 * Адрес одного объявления о конференции. Функция, а не шаблон по месту,
 * по той же причине, что у `newsItemRoute`: адрес собирают список
 * и — с F-45 — админка, а склейка строкой разъезжается при первом
 * переименовании.
 */
export function conferenceRoute(id: number): string {
  return `${CONFERENCES_ROUTE}/${id}`;
}

/**
 * Достижения кафедры. Адрес взят из меню
 * (`shared/config/navigation.ts`, пункт `scientific-activities/achievements`)
 * и повторяет старый портал — как и остальные перенесённые разделы,
 * это экономит строку в карте редиректов nginx при переезде.
 *
 * Знают четверо: список роутов, сама страница (собирает адреса пагинатора),
 * детальная (ссылка «ко всем достижениям») и блок достижений на карточке
 * ППС — оттуда открывается то же самое достижение, своего адреса
 * у персональных достижений нет.
 */
export const ACHIEVEMENTS_ROUTE = '/scientific-activities/achievements';

/**
 * Адрес одного достижения. Функция, а не шаблон по месту, по той же
 * причине, что у `newsItemRoute`: адрес собирают список, блок на карточке
 * ППС и — с F-45 — админка, а склейка строкой в трёх местах разъезжается
 * при первом переименовании.
 */
export function achievementRoute(id: number): string {
  return `${ACHIEVEMENTS_ROUTE}/${id}`;
}

/**
 * Профессорско-преподавательский состав. Адрес взят из меню
 * (`shared/config/navigation.ts`, пункт `about/employee/teachers`)
 * и повторяет старый портал — как и остальные перенесённые разделы,
 * это экономит строку в карте редиректов nginx при переезде.
 *
 * Знают трое: список роутов, сама страница (собирает адреса пагинатора)
 * и карточка преподавателя — ссылка «ко всем преподавателям».
 */
export const TEACHERS_ROUTE = '/about/employee/teachers';

/**
 * Адрес карточки одного преподавателя. Функция, а не шаблон по месту:
 * адрес собирают список, страница карточки и — с F-25 — детальная
 * достижения, где имя преподавателя ведёт на его карточку; склейка строкой
 * в трёх местах разъезжается при первом переименовании.
 *
 * `id` здесь — идентификатор **карточки**, не учётной записи: карточка
 * живёт отдельно от неё, и учётной записи у преподавателя может не быть
 * вовсе (docs/API.md, «Преподаватели»).
 */
export function teacherRoute(id: number): string {
  return `${TEACHERS_ROUTE}/${id}`;
}

/**
 * Учебно-вспомогательный персонал. Адрес взят из меню
 * (`shared/config/navigation.ts`, пункт `about/employee/uvp`) и повторяет
 * старый портал — как и остальные перенесённые разделы, это экономит
 * строку в карте редиректов nginx при переезде.
 *
 * Знают двое: список роутов и сама страница (собирает адреса пагинатора).
 * Функции адреса одной карточки — как `teacherRoute` у ППС — нет вовсе:
 * детальной страницы у УВП не было в оригинале и нет в контракте смысла —
 * карточка целиком помещается в элементе списка (docs/API.md, «УВП»).
 */
export const HELPERS_ROUTE = '/about/employee/uvp';
