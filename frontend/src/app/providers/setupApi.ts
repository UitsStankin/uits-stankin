import { setUnauthorizedHandler } from '@shared/api';
import { LOGIN_ROUTE } from '@shared/config/routes';

import { router } from '../routes';
import { queryClient } from './queryClient';

/**
 * Связывает api-клиент с приложением: объясняет ему, что делать,
 * когда сессия закончилась окончательно.
 *
 * «Окончательно» — потому что решение принимает не этот файл: обычный 401
 * означает лишь протухший access-токен, и клиент сначала пробует обменять
 * refresh-cookie на новый (`shared/api/client.ts`). Сюда доходит только то,
 * что обменом не лечится: истёкшая или погашенная сессия, выключенная
 * учётная запись, смена пароля в другом месте.
 *
 * Разворот зависимости, а не прямой импорт: интерцептор лежит на слое
 * `shared`, которому по FSD нельзя знать ни про роутер, ни про кэш запросов —
 * а слою `app` можно знать про всё. Заодно это единственный способ уйти
 * от `window.location.href`: полная перезагрузка страницы ради редиректа
 * выбрасывает кэш, состояние форм и историю навигации, тогда как
 * `router.navigate` остаётся внутри SPA.
 *
 * Кэш чистится целиком, а не выборочно: в нём лежат ответы, полученные
 * под прежним токеном, и после смены пользователя они показали бы чужие
 * данные до первого перезапроса.
 *
 * Вызывается из `main.tsx` до первого рендера — 401 может прилететь
 * на самом первом запросе.
 */
export function setupApi(): void {
  setUnauthorizedHandler(() => {
    queryClient.clear();

    // На форме входа мы уже стоим — увести успел `ProtectedRoute`. Его
    // `state.from` точнее: он помнит страницу, а мы к этому моменту помним
    // уже саму форму входа, и переход поверх подсунул бы `useLogin` адрес
    // возврата «на логин», то есть на главную. Заодно не остаётся лишней
    // записи в истории. Кто из двоих успеет первым, не определено: сессию
    // гасит один и тот же вызов, а дальше React перерисовывает дерево
    // и роутер переходит независимо друг от друга.
    if (router.state.location.pathname === LOGIN_ROUTE) return;

    // Иначе увести некому: страница была публичной или защиты на ней нет.
    // Адрес — в `state`, как это делает `ProtectedRoute`, чтобы после входа
    // вернуть человека туда, где его застала протухшая сессия.
    void router.navigate(LOGIN_ROUTE, { state: { from: router.state.location } });
  });
}
