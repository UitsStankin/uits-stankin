import { setUnauthorizedHandler } from '@shared/api';
import { LOGIN_ROUTE } from '@shared/config/routes';

import { router } from '../routes';
import { queryClient } from './queryClient';

/**
 * Связывает api-клиент с приложением: объясняет ему, что делать,
 * когда сессия перестала действовать.
 *
 * Разворот зависимости, а не прямой импорт: интерцептор лежит на слое
 * `shared`, которому по FSD нельзя знать ни про роутер, ни про кэш запросов —
 * а слою `app` можно знать про всё. Заодно это единственный способ уйти
 * от `window.location.href`: полная перезагрузка страницы ради редиректа
 * выбрасывает кэш, состояние форм и историю навигации, тогда как
 * `router.navigate` остаётся внутри SPA.
 *
 * Кэш чистится целиком, а не выборочно: в нём лежат ответы, полученные
 * под прежним токеном, и после смены пользователя они показали бы чужие
 * данные до первого перезапроса.
 *
 * Вызывается из `main.tsx` до первого рендера — 401 может прилететь
 * на самом первом запросе.
 */
export function setupApi(): void {
  setUnauthorizedHandler(() => {
    queryClient.clear();
    void router.navigate(LOGIN_ROUTE);
  });
}
