import type { PostType } from '@shared/types';

/**
 * Подпись типа записи.
 *
 * Метка на карточке появилась не для красоты: публичная ручка отдаёт новости
 * и объявления одним списком — фильтра по `postType` у неё нет (см. `newsApi`).
 * Пока его не заведут, метка — единственное, что отличает одно от другого,
 * и убирать её вместе с появлением фильтра не придётся: на детальной странице
 * она всё равно полезна.
 */
const POST_TYPE_LABELS: Record<PostType, string> = {
  news: 'Новость',
  announcements: 'Объявление',
};

export function postTypeLabel(postType: PostType): string {
  // Не `POST_TYPE_LABELS[postType]` без запасного варианта: enum'а на бэкенде
  // нет, `postType` — строка с `@Pattern`, и третье значение туда попадёт
  // раньше, чем сюда доедет обновлённый тип (ONBOARDING, `NewsRequestDto`).
  return POST_TYPE_LABELS[postType] ?? 'Запись';
}

/**
 * Имя автора либо `null` — «показывать нечего».
 *
 * Маппер бэкенда склеивает имя и фамилию, отбрасывая незаполненные части,
 * и отдаёт `null`, если не осталось ничего (`NewsMapper.authorName`).
 * Заполненная одна часть приходит одна — это нормальное значение, а не брак.
 *
 * Пустая строка обрабатывается наравне с `null`, хотя контракт её больше
 * не обещает: так эта функция переживает и старый стенд, который до сих пор
 * отдаёт `""`, и появление в базе имени из одних пробелов. Проверка дешевле
 * разбирательства, почему после слова «Автор» пустое место.
 */
export function authorLabel(authorName: string | null): string | null {
  const trimmed = authorName?.trim() ?? '';
  return trimmed.length > 0 ? trimmed : null;
}
