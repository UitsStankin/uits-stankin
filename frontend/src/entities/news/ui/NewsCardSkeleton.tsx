/**
 * Серый силуэт карточки на время первой загрузки.
 *
 * Лежит рядом с `NewsCard`, а не в странице, по одной причине: он обязан
 * повторять её раскладку — обложка слева, четыре строки справа, те же
 * отступы, — иначе в момент ответа список дёрнется по высоте. Замечать
 * расхождение можно только когда карточка и её силуэт лежат соседями;
 * разъехавшись по слоям, они разъедутся и по вёрстке.
 *
 * `aria-hidden`: диктору серые прямоугольники не говорят ничего, для него
 * загрузка проговаривается словами — это делает вызывающий, потому что
 * текст у ленты и у блока на главной разный.
 *
 * Пульсацию и число повторов задаёт вызывающий: на ленте видно три карточки
 * до первого экрана, а на главной под редактируемым блоком — сколько
 * получится.
 */
export function NewsCardSkeleton() {
  return (
    <div aria-hidden className="flex flex-col gap-4 rounded bg-white p-5 shadow-sm sm:flex-row">
      <div className="h-32 w-full shrink-0 rounded bg-gray-200 sm:w-56" />
      <div className="flex flex-1 flex-col gap-3 py-1">
        <div className="h-3 w-40 rounded bg-gray-200" />
        <div className="h-5 w-3/4 rounded bg-gray-200" />
        <div className="h-3 w-full rounded bg-gray-200" />
        <div className="h-3 w-5/6 rounded bg-gray-200" />
      </div>
    </div>
  );
}
