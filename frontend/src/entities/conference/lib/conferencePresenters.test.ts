import { afterAll, describe, expect, it, vi } from 'vitest';

/**
 * Пояс западнее Гринвича выставляется **до импорта модуля** — в этом весь
 * тест. Ошибка, от которой защищается разбор по компонентам, — `new
 * Date('2026-10-14')` считает голую дату полуночью UTC, и западнее Гринвича
 * она показывается 13-м, — на машине в московском поясе не воспроизводится
 * вовсе: там UTC-полночь — это три часа ночи того же дня, и наивный разбор
 * прошёл бы все проверки. Нью-Йорк делает сдвиг видимым везде.
 *
 * Импорт динамический, потому что форматтер создаётся один раз на модуль
 * и запоминает пояс в момент создания: выставленный после импорта пояс
 * не изменил бы ничего.
 */
vi.stubEnv('TZ', 'America/New_York');
const { conferenceDatesLabel } = await import('./conferencePresenters');

afterAll(() => {
  vi.unstubAllEnvs();
});

/**
 * ICU разделяет числа и «г.» то обычным пробелом, то узким неразрывным
 * (U+202F), и от версии к версии это менялось. Какой именно пробел — не то,
 * что здесь проверяется, поэтому все пробельные символы приводятся
 * к обычному. Тире остаётся как есть: диапазон собирает именно оно (U+2013),
 * и дефис на его месте значил бы, что строка склеена руками, а не ICU.
 */
function normalized(label: string | null): string | null {
  return label?.replace(/\s/g, ' ') ?? null;
}

describe('conferenceDatesLabel', () => {
  it('однодневная (endDate: null) — одна дата, не диапазон', () => {
    expect(normalized(conferenceDatesLabel('2026-10-14', null))).toBe('14 октября 2026 г.');
  });

  it('диапазон в одном месяце схлопывает повторы месяца и года', () => {
    expect(normalized(conferenceDatesLabel('2026-10-14', '2026-10-16'))).toBe(
      '14–16 октября 2026 г.',
    );
  });

  it('диапазон через границу месяца называет оба месяца', () => {
    expect(normalized(conferenceDatesLabel('2026-09-30', '2026-10-02'))).toBe(
      '30 сентября – 2 октября 2026 г.',
    );
  });

  it('диапазон через границу года называет оба года', () => {
    expect(normalized(conferenceDatesLabel('2026-12-30', '2027-01-02'))).toBe(
      '30 декабря 2026 г. – 2 января 2027 г.',
    );
  });

  it('без даты начала — null, даже при заданном конце', () => {
    expect(conferenceDatesLabel(null, null)).toBeNull();
    // Пара «конец без начала» не сохраняется по контракту, но рисовать
    // одинокий конец диапазона всё равно не по чему.
    expect(conferenceDatesLabel(null, '2026-10-16')).toBeNull();
  });

  it('на мусоре — null, а не Invalid Date', () => {
    expect(conferenceDatesLabel('14.10.2026', null)).toBeNull();
    expect(conferenceDatesLabel('', null)).toBeNull();
  });

  /**
   * `new Date(2026, 1, 30)` молча перекатывается во 2 марта — «30 февраля»
   * из битых данных показалось бы настоящей датой, а не отсутствием даты.
   */
  it('несуществующий день месяца — null, а не перекат в соседний месяц', () => {
    expect(conferenceDatesLabel('2026-02-30', null)).toBeNull();
  });
});
