/**
 * Человек в списке благодарностей.
 *
 * Ключа `id` у него нет, в отличие от оригинала. Там числа шли
 * 1…13, 15…17 — четырнадцатого кто-то удалил, и дыра переехала бы сюда
 * вместе с данными. Искать человека по номеру некому: список статический,
 * ручки у него нет и не будет, ссылок на карточку тоже. Единственное,
 * ради чего номер существовал, — ключ React, а имена в списке уникальны
 * и меняются реже, чем порядок.
 */
export interface Contributor {
  /** ФИО так, как его написали в оригинале. Он же ключ списка. */
  name: string;

  /** Роль в работе над порталом: «Тимлид», «Backend-разработчик». */
  role: string;

  /**
   * Фотография. У шестерых её нет — вместо неё общая заглушка портала,
   * та же, что у пользователя без аватара.
   */
  photo?: {
    src: string;
    width: number;
    height: number;
  };
}

