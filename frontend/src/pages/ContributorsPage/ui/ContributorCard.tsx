import { DEFAULT_AVATAR_URL } from '@shared/config/avatar';

import type { Contributor } from '../lib/contributors';

interface ContributorCardProps {
  contributor: Contributor;
}

/**
 * Один человек в списке благодарностей. Чистая: всё приходит пропсом,
 * состояния нет.
 *
 * Раскладка та же, что у карточек ППС и УВП, — круглое фото сверху,
 * подписи под ним, — и намеренно: на портале это третий список людей,
 * и выглядеть он должен как два первых. Свой компонент, а не `HelperCard`
 * из `entities/helper`, потому что там карточка контракта с `avatarUrl`
 * и должностью, а здесь строчка из кода с ролью в проекте — общей у них
 * только вёрстка, и склеивать их значило бы подгонять статический список
 * под форму, которую бэкенд волен менять.
 *
 * Карточка не ссылка и без подъёма по наведению: открывать по ней нечего.
 * То же решение, что у УВП.
 *
 * У шестерых снимка нет — вместо него общая заглушка портала. В оригинале
 * так же, только заглушка называлась `AVATAR_DEFAULT_URL`; подстановка
 * живёт в компоненте, а не в данных, как у всех остальных мест портала,
 * где показывают человека.
 */
export function ContributorCard({ contributor }: ContributorCardProps) {
  const { name, role, photo } = contributor;

  return (
    <article className="flex h-full flex-col items-center gap-3 rounded bg-white p-5 text-center shadow-sm">
      <img
        src={photo?.src ?? DEFAULT_AVATAR_URL}
        // Снимок декоративный: имя стоит подписью прямо под ним, и «фото
        // Малова Яна» диктор прочитал бы вторым заходом. В оригинале
        // в `alt` подставлялось то же имя.
        alt=""
        aria-hidden
        // Размеры — фактические, чтобы место под кружок было занято
        // до загрузки: шестнадцать карточек иначе прыгают все разом.
        // У заглушки свои: 1920×1164, растровая картинка портала.
        width={photo?.width ?? 1920}
        height={photo?.height ?? 1164}
        // Шестнадцать снимков; без `lazy` они уезжают в сеть все разом
        // ещё до первого экрана. То же, что у списка УВП.
        loading="lazy"
        className="h-28 w-28 shrink-0 rounded-full object-cover"
      />

      {/* h2, а не h3, как в карточках ППС и УВП: те лежат в `entities`
          и не знают, на какой глубине их поставят, — здесь карточка своя
          у страницы, и между ней и `h1` нет ничего. Размер задаёт токен
          `text-h5`, так что от соседних списков она не отличается. */}
      <h2 className="text-h5 text-text-heading">{name}</h2>

      <p className="text-base text-text-muted">{role}</p>
    </article>
  );
}
