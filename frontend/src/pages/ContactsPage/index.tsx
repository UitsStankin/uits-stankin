import EditableSection from '@widgets/EditableSection';

import { ContactsMap } from './ui/ContactsMap';
import { DepartmentChat } from './ui/DepartmentChat';

/**
 * Контакты кафедры. Сборка: карта слева, редактируемый раздел и чат
 * справа — раскладка оригинала.
 *
 * Страница смешанная, и этим отличается от разделов F-23: текст «как нас
 * найти» приходит с бэкенда редактируемым разделом `contacts`, а карта
 * и чат вокруг него свёрстаны руками. Ровно об этом предупреждала оговорка
 * блока 3 бэклога — свериться с F-23 прежде, чем верстать: у контактов
 * редактируемая часть была готова с F-23, своей осталась обёртка.
 *
 * Пустой раздел объясняется надписью, а не прячется, как блоки главной:
 * на чистой базе (`008-seed-editable-pages` заводит `contacts` с пустым
 * текстом) колонка рядом с картой иначе выглядела бы обрывом вёрстки.
 * Решение живёт в виджете и общее у всех трёх мест.
 *
 * Ширина `max-w-5xl`, как у главной, а не `max-w-4xl` разделов: здесь две
 * колонки рядом, и в комфортной для одного текста ширине карта ужимается
 * до полоски.
 *
 * Пропорции 60/35 и перелом раскладки — из SCSS оригинала (`flex: 1 1 60%`
 * против `1 1 35%`). Перелом там стоял на 768px, здесь на 992px (`lg`,
 * брейкпоинт каркаса портала): на планшете в книжной ориентации колонка
 * контактов сжималась до трёх слов в строке — адрес переносился по слогам.
 */
export default function ContactsPage() {
  return (
    <div className="mx-auto flex w-full max-w-5xl flex-col gap-gutter">
      <h1 className="text-h4 text-text-heading">Контакты</h1>

      {/* items-start обязателен: без него колонка растягивается по высоте
          карты, и карточка текста тянется пустым белым полем до её низа. */}
      <div className="flex flex-col gap-gutter lg:flex-row lg:items-start">
        <ContactsMap className="lg:basis-3/5" />

        <div className="flex flex-col gap-gutter lg:basis-2/5">
          <EditableSection slug="contacts" />

          <DepartmentChat />
        </div>
      </div>
    </div>
  );
}
