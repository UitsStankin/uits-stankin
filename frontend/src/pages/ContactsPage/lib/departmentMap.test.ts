import { describe, expect, it } from 'vitest';

import { departmentMapSrc } from './departmentMap';

/**
 * Адрес виджета карты.
 *
 * Проверять тут нечего глазами: карта — сторонний кадр, внутрь которого
 * jsdom не заглядывает, и метка посреди Кремля отрисовалась бы ровно так же
 * убедительно, как метка на Вадковском. Единственное, что отличает верную
 * карту от неверной без открытого браузера, — сама строка адреса.
 */
describe('departmentMapSrc', () => {
  /**
   * Ловушка, ради которой тест и написан: Яндекс ждёт «долгота, широта»,
   * а Google — «широта, долгота», и координаты сюда перенесены из
   * google-эмбеда оригинала. Переставленные местами, они дают точку
   * в Сомали — но кадр загрузится, и проверка на «карта на месте»
   * останется зелёной.
   */
  it('ставит координаты в порядке «долгота, широта»', () => {
    const params = new URL(departmentMapSrc()).searchParams;

    expect(params.get('ll')).toBe('37.593088,55.789498');
    expect(params.get('pt')).toBe('37.593088,55.789498');
  });

  it('открывает виджет Яндекса на масштабе дома', () => {
    const url = new URL(departmentMapSrc());

    expect(url.origin + url.pathname).toBe('https://yandex.ru/map-widget/v1/');
    expect(url.searchParams.get('z')).toBe('17');
  });
});
