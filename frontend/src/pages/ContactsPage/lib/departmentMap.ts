/**
 * Точка кафедры на карте.
 *
 * Числа перенесены из оригинала — единственное, чему в его карте можно
 * верить (разбор вранья остального — в `ui/ContactsMap.tsx`). В `pb`-строке
 * старого Google-эмбеда они лежали параметрами `!3d55.789498` и
 * `!2d37.593088` и указывают на Вадковский переулок, где стоит корпус.
 *
 * **Адреса строкой здесь намеренно нет.** Текст «как нас найти» — это
 * редактируемый раздел `contacts`, который правит модератор; вторая копия
 * адреса в коде фронта стала бы вторым источником правды, и разошлись бы
 * они молча. По той же причине на главной нет запасного текста для пустого
 * блока (`pages/HomePage`).
 *
 * Обратная сторона решения: метка стоит там, где сказано здесь, а адрес
 * пишет модератор — если он переедет, метка соврёт. Правильное лечение —
 * координаты в самом разделе, но поля под них в контракте нет
 * (docs/API.md, «Редактируемые страницы»: у раздела только `title`
 * и `text`), и заводить его ради одной метки — работа бэкенда, а не эта.
 */
const DEPARTMENT_POINT = {
  latitude: 55.789498,
  longitude: 37.593088,
} as const;

/**
 * Масштаб. 17 — дом различим вместе с соседними переулками; на 18 корпус
 * занимает экран целиком и непонятно, откуда к нему идти, на 16 Вадковский
 * теряется в сетке улиц.
 */
const ZOOM = 17;

/**
 * Адрес виджета карты.
 *
 * Собирается функцией, а не лежит готовой строкой, ровно ради теста: у карты
 * нет ни одного видимого признака, по которому проверка в jsdom отличила бы
 * верную метку от метки посреди Москвы, — а разъехавшуюся широту с долготой
 * (Яндекс ждёт их в порядке «долгота, широта», Google — наоборот) поймает
 * только сравнение строки.
 *
 * У `pt` нет кода стиля метки (`pm2rdm` и прочие из Static API): проверено
 * в браузере — виджет его молча игнорирует и рисует свою метку по умолчанию.
 * Оставленный код выглядел бы работающей настройкой, которой не является.
 */
export function departmentMapSrc(): string {
  const point = `${DEPARTMENT_POINT.longitude},${DEPARTMENT_POINT.latitude}`;

  const params = new URLSearchParams({
    ll: point,
    z: String(ZOOM),
    pt: point,
  });

  return `https://yandex.ru/map-widget/v1/?${params}`;
}
