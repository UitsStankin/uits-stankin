import { cn } from '@shared/lib';

import { departmentMapSrc } from '../lib/departmentMap';

interface ContactsMapProps {
  className?: string;
}

/**
 * Карта проезда — левая колонка контактов.
 *
 * ### Почему Яндекс, а не Google, как в оригинале
 *
 * Копировать было нечего: `pb`-строка старого эмбеда собрана руками
 * и врёт в двух местах из трёх. Подпись места (`!2z`) декодируется
 * из base64 в «Матаулиця ул., 1, Бистоиная Роская область» — испорченный
 * набор букв, а не адрес; метка времени (`!4v1699219200000`) — ровная
 * полночь 6 ноября 2023 UTC, тогда как Google выдаёт момент нажатия
 * «скопировать код». Верны в ней только координаты, и они перенесены
 * (`lib/departmentMap.ts`). Адрес виджета пришлось бы писать заново
 * в любом случае — вопрос был лишь в том, чей.
 *
 * При равном выборе решили три вещи:
 *
 * * **Читатели портала в России**, и Google Maps здесь грузится через раз.
 *   Карта, которой нет, хуже отсутствия карты: место под неё уже занято.
 * * **Кафедра — подразделение государственного вуза.** Сторонний кадр
 *   на публичной странице отдаёт хозяину кадра адрес страницы и IP
 *   посетителя; для зарубежного сервиса это разговор про 152-ФЗ,
 *   которого с российским не возникает.
 * * **Адрес виджета Яндекса собирается из координат** и читается глазами
 *   (`ll`, `z`, `pt`), а `pb` Google — непрозрачный блоб, в котором
 *   и завелось враньё оригинала: заметить его можно было только декодировав
 *   base64 вручную.
 *
 * Решение стоит подтвердить у кафедры — записано в бэклоге рядом с F-32.
 * Замена — одна функция в `lib/departmentMap.ts`.
 *
 * ### Мелочи
 *
 * `loading="lazy"` — карта ниже сгиба на телефоне и не нужна для первого
 * экрана; без него сторонний кадр тормозит загрузку страницы, ради которой
 * пришли читать телефон и почту.
 *
 * `title` обязателен: без него диктор читает кадр как «фрейм» без всякого
 * объяснения. В оригинале его не было — как и `alt` у иконки телеграма.
 *
 * Высота фиксированная, как в оригинале (400px), но на телефоне ниже:
 * там 400px съедали весь экран, и до текста контактов надо было
 * прокручивать.
 */
export function ContactsMap({ className }: ContactsMapProps) {
  return (
    <div className={cn('overflow-hidden rounded bg-white shadow-sm', className)}>
      <iframe
        src={departmentMapSrc()}
        title="Карта: расположение кафедры"
        loading="lazy"
        className="block h-75 w-full border-0 lg:h-100"
      />
    </div>
  );
}
