import Markdown from '@shared/ui/Markdown';

interface HomeBlockProps {
  /** Готовый Markdown или `null` — тогда блока не будет вовсе. */
  text: string | null;
}

/**
 * Редактируемый блок главной — `home-before` или `home-after`.
 *
 * Чистый: получает готовый текст и рисует его. Решение «рисовать или нет»
 * принято в модели, здесь только исполняется.
 *
 * Пустой блок не рисуется **вовсе** — ни карточки, ни отступа. Белый
 * прямоугольник с надписью «раздел пока не заполнен» на главной сообщал бы
 * посетителю о внутренней кухне портала то, что ему знать незачем;
 * у страницы, в отличие от раздела из F-23, собственного адреса
 * у блока нет, и пустое место здесь честнее подписи.
 *
 * Карточка та же, что у статьи новости (`bg-white`, `shadow-sm`, те же
 * отступы): фон портала серый, и текст, положенный прямо на него,
 * выглядел бы потерянным куском вёрстки.
 */
export function HomeBlock({ text }: HomeBlockProps) {
  if (text === null) return null;

  return (
    <section className="rounded bg-white p-6 shadow-sm md:p-8">
      <Markdown text={text} />
    </section>
  );
}
