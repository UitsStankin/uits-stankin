import { useEffect, useRef, useState } from 'react';
import { useSearchParams } from 'react-router';

import { SEARCH_PARAM, parseSearch } from '@shared/lib';

/**
 * Пауза между последней нажатой клавишей и запросом.
 *
 * 300 мс — обычная скорость набора: между буквами одного слова проходит
 * меньше, между словами — примерно столько. То есть запрос уходит
 * на паузу в наборе, а не на каждую букву: без задержки «чеканин»
 * стоил бы семи запросов и семи записей в адресной строке.
 */
const SEARCH_DEBOUNCE_MS = 300;

/**
 * Поле поиска: что в нём набрано и когда это уезжает в адрес.
 *
 * **Источник правды — адрес, а не поле.** Список читает `?q=` оттуда же,
 * откуда номер страницы, поэтому поиск переживает перезагрузку, ссылку
 * и кнопку «назад». Поле держит своё состояние ровно по одной причине:
 * между нажатием клавиши и запросом стоит пауза, и всё это время
 * набранное должно быть видно.
 *
 * ### Две стороны синхронизации и почему нужен `ref`
 *
 * Состояний, которые обязаны сходиться, два: набранное в поле и лежащее
 * в адресе. Ходят они в обе стороны — набор двигает адрес, а «назад»
 * и внешняя ссылка двигают поле, — и наивная связка «поле ← адрес»
 * ломает набор: адрес хранит обрезанный запрос, и первый же пробел между
 * словами исчезал бы под курсором через 300 мс после нажатия.
 *
 * `written` помнит, что в адрес положили мы сами. Совпало — правку поля
 * не трогаем, это эхо собственной записи; не совпало — адрес сменил
 * кто-то другой, и поле обязано его догнать.
 */
export function usePostgraduateSearch() {
  const [searchParams, setSearchParams] = useSearchParams();
  const urlSearch = parseSearch(searchParams.get(SEARCH_PARAM));

  const [text, setText] = useState(urlSearch);
  const written = useRef(urlSearch);

  /**
   * Запрос в адрес. Набор параметров собирается заново, а не правится:
   * смена запроса обязана сбрасывать номер страницы. Искать со второй
   * страницы бессмысленно — под новый запрос её может не быть вовсе,
   * и человек получил бы «такой страницы нет» вместо результатов.
   *
   * Объявлена выше обоих эффектов не для красоты: правило компилятора
   * `react-hooks/immutability` запрещает звать функцию раньше объявления —
   * ранний вызов не увидел бы её пересоздания.
   */
  function applySearch(value: string, replace: boolean) {
    setSearchParams(value === '' ? {} : { [SEARCH_PARAM]: value }, { replace });
  }

  // Адрес сменили снаружи: «назад», «вперёд», чужая ссылка, наша же
  // ссылка «показать всех» из пустой выдачи.
  useEffect(() => {
    if (urlSearch === written.current) return;

    written.current = urlSearch;
    setText(urlSearch);
  }, [urlSearch]);

  // Набранное уезжает в адрес после паузы.
  useEffect(() => {
    const next = text.trim();
    if (next === written.current) return;

    const timer = setTimeout(() => {
      // Первый запрос в пустом поле — новой записью в истории: кнопка
      // «назад» обязана возвращать к полному списку. Уточнения запроса —
      // заменой, иначе история зарастает состояниями «че», «чек», «чека»,
      // и выйти из поиска «назад» становится нельзя.
      const replace = written.current !== '';

      written.current = next;
      applySearch(next, replace);
    }, SEARCH_DEBOUNCE_MS);

    return () => clearTimeout(timer);
  }, [text, setSearchParams]);

  /**
   * Кнопка «очистить» — сразу, без паузы: пауза нужна набору, а нажатие
   * однозначно и ждать себя не должно.
   */
  function clear() {
    setText('');
    written.current = '';
    applySearch('', true);
  }

  return { text, setText, clear };
}
