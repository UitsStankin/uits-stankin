import type { Profile } from '@shared/types';

/**
 * «Фамилия Имя» для карточки — порядок как в оригинале.
 *
 * Склейка через `filter`, а не шаблонной строкой: в контракте `firstName`
 * и `lastName` по отдельности могут быть `null`, и `${lastName} ${firstName}`
 * написал бы в карточке «Иванов null».
 *
 * Пустая строка, если не заполнено ни то, ни другое: чем заменить пустое
 * значение, решает карточка — и решает одинаково для всех своих полей.
 */
export function formatFullName(profile: Profile): string {
  return [profile.lastName, profile.firstName].filter(Boolean).join(' ');
}

/**
 * Уровень доступа словами.
 *
 * Список, а не одна строка: в контракте это три независимых булевых поля,
 * и они сочетаются — модератор бывает преподавателем. Оригинал показывал
 * одну роль по цепочке `*ngIf`, и такой пользователь выглядел просто
 * модератором.
 *
 * `teacher` показывается, но прав не даёт: это отметка владельца карточки
 * ППС, а не уровень доступа (docs/API.md, раздел «Роли»). Поэтому и стоит
 * последним — после тех двух, которые действительно что-то открывают.
 *
 * Пустого списка не бывает: у обычного пользователя все три флага сняты,
 * и вместо пустоты в карточке должно стоять «Пользователь» — иначе строка
 * выглядит недогруженной, а не заполненной.
 */
export function describeRoles(profile: Profile): string[] {
  const roles: string[] = [];

  if (profile.superuser) roles.push('Суперпользователь');
  if (profile.moderator) roles.push('Модератор');
  if (profile.teacher) roles.push('Преподаватель');

  return roles.length > 0 ? roles : ['Пользователь'];
}
