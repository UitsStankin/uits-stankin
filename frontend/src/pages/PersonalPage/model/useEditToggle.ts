import { useState } from 'react';

/**
 * Переключатель «смотрю — правлю» для карточки личного кабинета.
 *
 * Заведён для карточки ППС (F-16), вынесен вторым потребителем — карточкой
 * учётной записи (F-27). Обе живут по одним правилам: форма показывается
 * вместо карточки, «Отмена» возвращает чтение, успех возвращает чтение
 * и оставляет над карточкой строку «сохранено».
 *
 * Живёт в слайсе страницы, а не в `shared`: обе карточки — на ней одной,
 * и общий примитив «редактируемая секция» стоит заводить вместе с формами
 * админки (F-4x), когда станет видно, что у них те же правила.
 */
export function useEditToggle() {
  const [isEditing, setIsEditing] = useState(false);
  /**
   * «Сохранено» после выхода из формы. Отдельный флаг, а не
   * `mutation.isSuccess`: мутация живёт в форме, а форма после сохранения
   * размонтирована — сообщать об успехе больше некому.
   */
  const [justSaved, setJustSaved] = useState(false);

  return {
    isEditing,
    justSaved,
    startEditing: () => {
      setIsEditing(true);
      // Форму открыли снова — значит, «сохранено» относится к прошлому
      // разу и после новой отмены висело бы враньём.
      setJustSaved(false);
    },
    cancelEditing: () => setIsEditing(false),
    finishEditing: () => {
      setIsEditing(false);
      setJustSaved(true);
    },
  };
}
