import { useQuery } from '@tanstack/react-query';

import { editablePageQuery } from '@entities/editable-page';
import type { EditablePageSlug } from '@shared/types';

/**
 * Состояние страницы редактируемого раздела: один запрос по слагу и разбор
 * его состояний. Разметка о Query ничего не знает.
 *
 * **Слаг приходит пропом, а не разбирается из адреса** — этим страница
 * отличается от детальной новости с её `useParams`. Девять адресов разделов
 * фиксированы в таблице роутов (`app/routes/index.tsx`), и слаг там
 * захардкожен рядом с путём: опечатка в нём — ошибка компиляции
 * по `EditablePageSlug`, а не рантаймовый `404` на живой странице.
 *
 * Ветки «раздел не найден» здесь нет намеренно. `404` по известному слагу
 * означает не битую ссылку, а не доехавшую до стенда миграцию
 * (`entities/editable-page`) — для посетителя это тот же сбой сервера,
 * что и `500`: страница, на которую его привело меню, обязана существовать.
 * Отдельная надпись «раздела не существует» звучала бы как сломанный портал
 * и подсказывала бы внутреннюю кухню, починить которую может только
 * пересборка стенда.
 */
export function useEditablePageContent(slug: EditablePageSlug) {
  const query = useQuery(editablePageQuery(slug));

  // trim — тот же, что у блоков главной: строка из одних пробелов
  // и переводов строки — то же «не заполнено», но рисует пустую карточку.
  const text = query.data?.text.trim() ?? '';

  return {
    /** Markdown раздела — или `null`, пока рисовать нечего. */
    text: text || null,

    /** Первая загрузка: показывать скелет. */
    isLoading: query.isLoading,
    /**
     * Запрос приостановлен, и показать пока нечего: нет сети либо вкладка
     * в фоне. Ветка отдельная по той же причине, что и в ленте: при паузе
     * не выставлены ни `isLoading`, ни `isError` — подробный разбор
     * в `widgets/NewsFeed/model/useNewsList.ts`.
     */
    isOffline: query.isPaused && query.data === undefined,
    isError: query.isError,
    errorMessage: query.error?.message ?? null,

    /**
     * Раздел загружен, но модератор его ещё не заполнил, — состояние чистой
     * базы: ченджсет `008-seed-editable-pages` заводит все тринадцать
     * разделов с `text: ''`. Главная в этом случае не рисует блок вовсе,
     * потому что там он — необязательное обрамление ленты; здесь раздел —
     * всё содержимое страницы, и пустота без объяснения выглядела бы
     * поломкой.
     */
    isEmpty: query.isSuccess && text === '',

    refetch: () => void query.refetch(),
  };
}
