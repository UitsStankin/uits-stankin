/**
 * Событие ленты. Карточка бывает двух видов — с текстом и с фотографией
 * коллектива, — но отдельного признака для этого нет: рисуется то,
 * что заполнено.
 */
export interface HistoryEvent {
  /** Ключ для React. Год для этого не годится: 2010-й в ленте дважды. */
  id: string;

  /** Подпись на шкале: год или период. */
  period: string;

  /** Заголовок карточки. */
  title: string;

  /** Иконка события, декоративная. */
  icon: LucideIcon;

  /**
   * Рассказ о событии — **Markdown**, а не готовая разметка.
   *
   * В оригинале имена заведующих, названия программ и предприятий были
   * обёрнуты в `<span class="special-highlight">` — восемнадцать раз
   * на страницу. Правила `.special-highlight` в его SCSS нет **вовсе**
   * (435 строк, проверено), то есть замысел «выделить» остался
   * незакрытым: на живом сайте это обычный текст.
   *
   * Здесь те же места стали `**жирным**`. Абзацы длинные — по девять
   * строк, — и выделенные в них имена и названия дают глазу за что
   * зацепиться; цвет для этого выдумывать не пришлось.
   *
   * Markdown, а не JSX в данных, по двум причинам. Текст остаётся
   * текстом — данные не тянут за собой разметку; и показывает его
   * `shared/ui/Markdown` — тот же, что рисует редактируемые разделы,
   * то есть типографика у истории и у остальных текстов портала одна.
   */
  text?: string;

  /** Фотография коллектива вместо рассказа. */
  photo?: {
    src: string;
    /** Осмысленный, а не «Персонал кафедры УИТС» на оба снимка, как в оригинале. */
    alt: string;
    width: number;
    height: number;
  };

  /** Метки под текстом: имена, программы, партнёры. */
  highlights?: readonly string[];
}

