/**
 * Доля прочитанного, 0–100, по трём измерениям окна.
 *
 * Отдельной функцией, а не строкой внутри хука: это единственная
 * арифметика на странице, и проверять её удобнее без окна браузера —
 * подстановка `scrollHeight` в jsdom стоила бы дороже самой проверки.
 *
 * Целые проценты, а не дробь. Полоса высотой 4 пикселя разницы
 * не покажет, зато у хука на `useSyncExternalStore` от округления
 * появляется полезное свойство: прокрутка на пиксель чаще всего
 * не меняет снимок вовсе, и страница не перерисовывается.
 *
 * @param scrollY        сколько пролистано сверху, `window.scrollY`
 * @param pageHeight     вся высота документа, `scrollHeight`
 * @param viewportHeight видимая часть окна, `innerHeight`
 */
export function scrollProgressPercent(
  scrollY: number,
  pageHeight: number,
  viewportHeight: number,
): number {
  const scrollable = pageHeight - viewportHeight;

  // Страница короче окна — прокручивать нечего. В оригинале этой проверки
  // не было: деление на ноль давало `NaN`, полоса получала `width: NaN%`,
  // и браузер такое правило молча выбрасывал — то есть на короткой странице
  // индикатор просто застревал на прошлом значении.
  if (scrollable <= 0) return 0;

  // Границы обрезаются: `scrollY` уезжает и за них — резиновая прокрутка
  // в Safari даёт отрицательные значения сверху и больше высоты снизу.
  const percent = (scrollY / scrollable) * 100;
  return Math.min(100, Math.max(0, Math.round(percent)));
}
