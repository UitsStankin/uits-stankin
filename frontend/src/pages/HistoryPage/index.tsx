import { HISTORY_TIMELINE } from './lib/historyTimeline';
import { useScrollProgress } from './model/useScrollProgress';
import { HistoryHero } from './ui/HistoryHero';
import { HistoryTimeline } from './ui/HistoryTimeline';
import { ScrollProgress } from './ui/ScrollProgress';

/**
 * История кафедры. Сборка: единственное состояние берётся из модели,
 * разметка — из чистых компонентов, содержимое — из данных в `lib/`.
 *
 * Страница статическая: ручки у неё нет и не будет. Проверено при закрытии
 * F-23 — в `editable_pages` старого портала истории не было, это ровно
 * та вёрстка руками, о которой предупреждает блок 3 бэклога.
 *
 * ### Что не перенесено
 *
 * **Плитка «22 года развития»** — четыре числа под лентой: 500 выпускников,
 * 9 защищённых диссертаций, 6 образовательных программ, 25 профильных
 * дисциплин. Захардкожены в разметке оригинала, источника нет, и первое же
 * из них спорит с заготовкой главной, где выпускников «850+» (F-17).
 * Показывать посетителю два разных числа на одном портале хуже, чем
 * не показывать ни одного. Решение то же, что в F-25 с такой же плиткой
 * над достижениями: числа возвращаются данными — подтверждёнными
 * заказчиком и через форму правки, — а не константами в коде фронта.
 * Из четырёх подтверждено ровно одно, и оно и так есть в тексте события
 * 2009 года.
 *
 * **Оформление без содержания** — три плавающих кружка и фоновая сетка
 * в шапке, подъём карточки при наведении (карточка никуда не ведёт),
 * выезд событий по очереди с задержкой до 1.2 с. Последний к тому же был
 * сделан наполовину: задержки прописаны шести карточкам из десяти,
 * остальные появлялись сразу.
 *
 * ### Что поправлено по дороге
 *
 * Год на девятой карточке (`2010` при заголовке «...в 2023 году») и подписи
 * обеих фотографий — обе были «Персонал кафедры УИТС». Разбор — в данных.
 *
 * ### Что осталось спросить
 *
 * Последнее событие названо «2022–2025» — так его написали в 2025 году,
 * и закрытый период означает, что эпоха кончилась. Сегодня 2026-й, и это
 * либо устаревшая подпись, либо смена заведующего, о которой мы не знаем.
 * Текст кафедры мы не выдумываем: вопрос записан в бэклоге рядом с F-30.
 */
export default function HistoryPage() {
  const percent = useScrollProgress();

  return (
    <div className="mx-auto flex w-full max-w-4xl flex-col gap-gutter">
      <ScrollProgress percent={percent} />

      <HistoryHero />

      <HistoryTimeline events={HISTORY_TIMELINE} />
    </div>
  );
}
