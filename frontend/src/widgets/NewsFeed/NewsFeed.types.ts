import type { PostType } from '@shared/types';

export interface NewsFeedProps {
  /**
   * Какие записи показывать. Отбор делает бэкенд — параметр уходит
   * в запрос, а не применяется к ответу: счётчики страниц считает база,
   * и фильтрация выдачи на клиенте ломает пагинацию, а не чинит список.
   */
  postType: PostType;
  /**
   * Адрес раздела, которому принадлежит лента: `/about/news`
   * или `/about/announcements`. Из него собираются ссылки пагинатора,
   * поэтому виджет и не берёт его из роутера сам — иначе `?page=2`
   * на одном разделе уводил бы на другой при первом же переиспользовании.
   */
  route: string;
}
