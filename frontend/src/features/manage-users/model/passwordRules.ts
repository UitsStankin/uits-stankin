import { z } from 'zod';

/**
 * Предел bcrypt — в **байтах**, а не в символах: русская буква в UTF-8
 * занимает два, и 36 кириллических символов уже упираются в него
 * (docs/API.md, «Смена пароля»). Считать символами значило бы пропустить
 * пароль, который сервер отвергнет `400`.
 */
const BCRYPT_MAX_BYTES = 72;

/**
 * Правило нового пароля — одно на создание учётки и на сброс: у обеих
 * ручек на бэкенде одна и та же пара `@Size(min = 8)` и `@BcryptCompatible`.
 *
 * Текст про минимум — серверный дословно, как у смены пароля: одна
 * ошибка не должна выглядеть по-разному в зависимости от того, кто её
 * заметил. Про байты — свой: серверное «длиннее 72 байт в UTF-8» человеку,
 * набравшему 40 букв, ничего не объясняет, а до сервера такой пароль
 * всё равно не доедет.
 */
export const newPasswordRule = z
  .string()
  .min(8, 'Пароль должен быть минимум 8 символов')
  .refine(
    (value) => new TextEncoder().encode(value).length <= BCRYPT_MAX_BYTES,
    'Пароль слишком длинный: не больше 72 байт, русская буква считается за два',
  );

/** Повтор пароля: ввод скрыт, и опечатку иначе узнают при первом входе. */
export const confirmPasswordRule = z.string().min(1, 'Повторите пароль');
