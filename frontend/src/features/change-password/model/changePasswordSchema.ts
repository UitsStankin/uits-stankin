import { z } from 'zod';

/**
 * Проверки формы смены пароля.
 *
 * Первые два поля повторяют бэкенд один в один (`ChangePasswordRequest`:
 * оба `@NotBlank`, новый — `@Size(min = 8)`), включая текст сообщения
 * о длине: одна и та же ошибка не должна выглядеть по-разному в зависимости
 * от того, кто её заметил — форма или сервер.
 *
 * Проверки «новый пароль не равен старому» здесь намеренно нет: бэкенд её
 * не делает, а форма не должна запрещать то, что сервер разрешает. Такой
 * запрет выглядит как правило системы, хотя на деле это выдумка клиента.
 */
export const changePasswordSchema = z
  .object({
    oldPassword: z.string().min(1, 'Введите текущий пароль'),
    newPassword: z.string().min(8, 'Пароль должен быть минимум 8 символов'),
    /**
     * Поле только клиентское — в теле запроса его нет и на бэкенде оно
     * неизвестно. Нужно потому, что ввод скрыт: опечатка в новом пароле
     * иначе обнаружится при следующем входе, то есть тогда, когда
     * исправить её уже нечем.
     */
    confirmPassword: z.string().min(1, 'Повторите новый пароль'),
  })
  .refine((values) => values.newPassword === values.confirmPassword, {
    message: 'Пароли не совпадают',
    // Без `path` ошибка стала бы ошибкой всей формы и повисла в баннере,
    // а не под тем полем, которое надо исправить.
    path: ['confirmPassword'],
  });

export type ChangePasswordFormValues = z.infer<typeof changePasswordSchema>;

/**
 * Поля, которые форма умеет подсветить, — по ним разбирается словарь
 * `errors` из ответа сервера. Сообщения для незнакомого поля класть некуда,
 * и они уходят в общий баннер.
 *
 * `confirmPassword` в списке есть, хотя сервер о нём не знает: список
 * описывает форму, а не контракт.
 */
export const CHANGE_PASSWORD_FIELDS = ['oldPassword', 'newPassword', 'confirmPassword'] as const;
