/**
 * Ключ файла аватара из его адреса. ВРЕМЕННЫЙ ОБХОД ДЫРЫ КОНТРАКТА —
 * удалить вместе с первым же расширением ответа `/api/teachers/me`.
 *
 * Дыра такая: `PUT /api/teachers/me` — полная замена, и поле `avatar` ждёт
 * **ключ** файла; не прислать его — значит стереть фото, причём бэкенд
 * удалит файл с диска физически. А обе ручки чтения отдают только готовый
 * адрес `avatarUrl` — ключа в `TeacherDetailsResponseDto` нет, хотя у
 * профиля и новостей пара «ключ и адрес» приходит целиком. То есть форма,
 * в которой преподаватель поправил телефон, не тронув фото, честного
 * способа сохранить это фото не имеет.
 *
 * Разбирать адрес запрещено правилом контракта («формат ключа — деталь
 * бэкенда», docs/API.md) — поэтому разбор изолирован в одну функцию
 * с охраной. Сегодня адрес собирается как `<public-base-url>/<key>`
 * (`LocalFileStorage.url`), база — `/media` и в dev, и в prod; изменится
 * правило сборки — функция вернёт `null`, и форма откажется сохранять,
 * предложив выбрать фото заново (загрузка даёт свежий ключ), а не сотрёт
 * его молча.
 */

const MEDIA_URL_PREFIX = '/media/';

export function avatarKeyFromUrl(avatarUrl: string): string | null {
  if (!avatarUrl.startsWith(MEDIA_URL_PREFIX)) return null;

  const key = avatarUrl.slice(MEDIA_URL_PREFIX.length);
  return key.length > 0 ? key : null;
}
