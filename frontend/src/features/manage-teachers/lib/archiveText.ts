/**
 * Что сделает архив карточки ППС — словами для окна подтверждения.
 *
 * Источник — контракт (docs/API.md, «Архив», T-120): архив убирает
 * карточку из публичных выдач и **блокирует привязанную учётную запись**,
 * а возврат из архива карточку возвращает, доступ — нет. Его включают
 * отдельно, в разделе учётных записей. Поэтому архив перестал быть
 * «обратимым одной кнопкой», и перед ним спрашивают.
 *
 * `userId` — три состояния, а не два: `number` — учётка привязана,
 * `null` — точно нет, `undefined` — неизвестно. Последнее у строки
 * таблицы: короткая карточка списка связи с учёткой не несёт
 * (`TeacherListItem`), и утверждать «учётки нет» там было бы неправдой.
 */
export function archiveDescription(name: string, userId?: number | null): string {
  const card = `Карточка «${name}» пропадёт из списков на сайте, по прямой ссылке она откроется. Расписание, достижения, записи аспирантуры и ведомости сохранятся.`;

  // «Администратор», а не «вы»: архивирует и модератор, а раздел учётных
  // записей открыт только админу (`adminNavigation.ts`).
  const account =
    userId === null
      ? ' Учётная запись к карточке не привязана.'
      : `${userId === undefined ? ' Если к карточке привязана учётная запись, она' : ' Привязанная учётная запись'} будет заблокирована: войти в личный кабинет преподаватель не сможет. Возврат из архива доступ не вернёт — включить учётную запись может только администратор в разделе «Учётные записи».`;

  return card + account;
}
