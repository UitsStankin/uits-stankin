import { useQuery } from '@tanstack/react-query';

import { clearSession, refreshAccessToken } from '@shared/api';

import { authKeys } from '../api/profileQuery';
import { useAccessToken, useHasSession } from './useSession';

/**
 * Возвращение в уже открытую сессию при запуске вкладки.
 *
 * Access-токен теперь живёт в памяти и умирает вместе с вкладкой, а вход
 * — нет: refresh-cookie у браузера остаётся на две недели. Перезагрузка
 * страницы без этого обмена выглядела бы как выход, то есть переезд токена
 * из `localStorage` обошёлся бы дороже, чем стоит.
 *
 * Обмен идёт **до** запроса профиля, а не в ответ на его 401. Так дешевле
 * (два запроса вместо трёх) и, главное, честнее: 401 от профиля
 * с несуществующей сессией — это «на логин», и посетитель с устаревшим
 * признаком сессии оказывался бы на форме входа, просто открыв главную.
 * Здесь такой ответ означает всего лишь «пришли гостем».
 *
 * Возвращает признак ожидания: пока обмен идёт, про пользователя
 * не известно ничего, и показывать «Вход для персонала» ещё рано.
 */
export function useRestoreSession(): boolean {
  const token = useAccessToken();
  const hasSession = useHasSession();

  const { isLoading } = useQuery({
    queryKey: authKeys.session,
    queryFn: async () => {
      const result = await refreshAccessToken();

      // Cookie не сработала — признак сессии врёт, и его надо снять здесь.
      // Обмен этого не делает намеренно: он только сообщает, чем кончилось,
      // а решают вызывающие, и решают по-разному (`shared/api/client.ts`).
      // Здесь решение — забыть признак и НЕ уводить на форму входа:
      // на старте вкладки это значит «пришли гостем», а не «вас выкинуло».
      // Без этой строки признак пережил бы запуск, и шапка ждала бы профиль,
      // которого не будет.
      if (result.status === 'expired') clearSession();

      // Токен запрос кладёт в сессию сам; здесь он нужен лишь как значение
      // кэша — `queryFn` обязана что-то вернуть, а `undefined` в TanStack
      // Query запрещён. `null` читается как «сессии не оказалось».
      return result.status === 'refreshed' ? result.token : null;
    },
    /**
     * Гостю обменивать нечего, а с токеном на руках — незачем. Признак
     * сессии реактивен, поэтому вход в соседней вкладке включит запрос
     * и здесь: токена у этой вкладки нет, а cookie у браузера общая.
     */
    enabled: hasSession && token === null,
    /**
     * Разовое действие на запуск вкладки: дальше токен обновляет
     * интерцептор в ответ на 401. Устаревать и перезапрашиваться
     * этому запросу незачем — каждый лишний обмен ротирует refresh-токен.
     */
    staleTime: Infinity,
    /**
     * Повторять нечего: 401 означает «сессии нет» и второй раз ответит
     * так же, а обрыв связи попробует ещё раз первый же запрос, который
     * налетит на 401. Общее правило клиента (`app/providers/queryClient.ts`)
     * повторило бы сетевую ошибку дважды и задержало бы шапку.
     */
    retry: false,
  });

  return isLoading;
}
