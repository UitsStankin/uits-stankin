import { z } from 'zod';

/**
 * Проверки формы входа — ровно те, что и на бэкенде: оба поля `@NotBlank`
 * в `AuthController.LoginRequest`, и больше ничего.
 *
 * Минимальной длины пароля здесь нет намеренно. Правило «не короче восьми»
 * относится к смене пароля (`ChangePasswordRequest`, тикет F-13), а не ко
 * входу: у заведённой раньше учётки пароль может быть короче, и форма
 * не пустила бы её владельца, ничего при этом не защитив.
 *
 * Логин обрезается по краям: его копируют из письма или из таблицы вместе
 * с пробелом, а сервер такой пробел не прощает — придёт 401 «неверный логин
 * или пароль», и понять причину по нему невозможно. С паролем так делать
 * нельзя: пробел в нём может быть значащим символом.
 */
export const loginSchema = z.object({
  username: z.string().trim().min(1, 'Введите логин'),
  password: z.string().min(1, 'Введите пароль'),
});

export type LoginFormValues = z.infer<typeof loginSchema>;

/**
 * Поля, которые форма умеет подсветить. Нужен списком, а не выводом из схемы:
 * по нему разбирается словарь `errors` из ответа сервера — сообщения
 * для неизвестного поля некуда положить, и они уходят в общий баннер.
 */
export const LOGIN_FIELDS = ['username', 'password'] as const;
