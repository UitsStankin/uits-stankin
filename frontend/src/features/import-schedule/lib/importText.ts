import { isApiError } from '@shared/api';
import { pluralize } from '@shared/lib';

/** Что импортируется: пары или экзамены — два документа и две ручки. */
export type ImportKind = 'lessons' | 'exams';

/**
 * Предел размера по контракту — 5 МБ. Сервер проверит его и сам (`400`),
 * но до этого файл придётся отправить целиком, а на медленной сети это
 * минута ожидания ради отказа, известного заранее.
 *
 * Тип файла здесь не проверяется: PDF это или нет, решает разбор
 * на сервере, и вторая проверка на клиенте была бы вторым источником
 * правды о том, «какой файл годится». Выбор в окне ограничен `accept`,
 * а всё, что пролезет мимо него, сервер отклонит своими словами.
 */
export const MAX_IMPORT_BYTES = 5 * 1024 * 1024;

const FORMS: Record<ImportKind, readonly [string, string, string]> = {
  lessons: ['занятие', 'занятия', 'занятий'],
  exams: ['экзамен', 'экзамена', 'экзаменов'],
};

/** Как называется документ — в заголовке строки и в тексте окна. */
export const KIND_TITLE: Record<ImportKind, string> = {
  lessons: 'Расписание пар',
  exams: 'Расписание экзаменов',
};

/** «24 занятия», «1 экзамен». */
export function countText(kind: ImportKind, count: number): string {
  return `${String(count)} ${pluralize(count, FORMS[kind])}`;
}

/**
 * Отказ ещё до отправки — `null`, если файл можно слать.
 *
 * Пустой файл ловится тоже: сервер ответил бы на него `400`, но выбранный
 * по ошибке пустой файл — это опечатка в выборе, и ждать ради неё ответа
 * незачем.
 */
export function checkImportFile(file: File): string | null {
  if (file.size === 0) return `Файл «${file.name}» пуст.`;
  if (file.size > MAX_IMPORT_BYTES) {
    return `Файл «${file.name}» больше 5 МБ — такой сервер не примет.`;
  }
  return null;
}

/**
 * Текст окна подтверждения. Импорт заменяет расписание **целиком**,
 * а ручек правки и отката в контракте нет: прежнее восстановить нечем,
 * кроме как загрузить прежний PDF. Поэтому окно называет, что именно
 * пропадёт, — числом, а не общим «текущее расписание».
 *
 * `currentCount` — `null`, когда текущее расписание прочитать
 * не удалось: тогда честнее сказать «если оно загружено», чем
 * промолчать или напугать несуществующей потерей.
 */
export function confirmText(kind: ImportKind, fileName: string, currentCount: number | null) {
  const what = KIND_TITLE[kind].toLowerCase();
  const source = `разобранным из файла «${fileName}»`;

  if (currentCount === 0) {
    return `Сейчас ${what} не загружено. Оно будет заполнено ${source}.`;
  }

  const current =
    currentCount === null
      ? `Текущее ${what}, если оно загружено,`
      : `Текущее ${what} (${countText(kind, currentCount)})`;

  return `${current} будет удалено и заменено ${source}. Вернуть прежнее можно только повторной загрузкой прежнего файла.`;
}

/**
 * Отказ импорта — словами, из которых ясно, **кому** чинить.
 *
 * Главное различие — `400` и `503` (docs/API.md): первое чинит человек,
 * выбравший файл, второе — администратор сервера, и «проверьте файл» при
 * лёгшем сервисе разбора отправило бы модератора искать ошибку там, где
 * её нет. У `400` слова сервера показываются как есть — в них причина
 * («в PDF не найдено ни одной таблицы расписания», день и пару
 * у слишком длинного поля), и пересказать их точнее нечем.
 *
 * Хвост «прежнее не тронуто» — у всех отказов, кроме обрыва сети: замена
 * идёт одной транзакцией, и упавший импорт расписание не портит. При
 * обрыве же ответа не было, и что успело случиться на сервере, неизвестно.
 */
export function importErrorMessage(kind: ImportKind, error: unknown): string {
  const kept = `${KIND_TITLE[kind]} осталось прежним.`;

  if (!isApiError(error)) return `Не удалось загрузить файл. ${kept}`;

  switch (error.status) {
    case 0:
      // Сюда же попадает тело тяжелее 20 МБ: контейнер обрывает его без
      // ответа. До отправки такой файл не доходит (`checkImportFile`),
      // так что остаётся настоящая сеть.
      return 'Нет связи с сервером. Загрузилось ли расписание, неизвестно — обновите страницу и посмотрите.';
    case 400:
      return `Файл не принят: ${sentence(error.message)} ${kept}`;
    case 409:
      return `Это расписание прямо сейчас загружает кто-то ещё. Подождите и повторите. ${kept}`;
    case 413:
      return `Файл слишком большой — сервер принимает до 5 МБ. ${kept}`;
    case 503:
      return `Сервис разбора расписаний сейчас недоступен — дело не в файле. Повторите позже; если не пройдёт, сообщите администратору сервера. ${kept}`;
    default:
      return `${sentence(error.message)} ${kept}`;
  }
}

/**
 * Слова сервера приходят и с точкой, и без («в PDF не найдено ни одной
 * таблицы расписания»), а за ними в сообщении идёт ещё одно предложение.
 */
function sentence(text: string): string {
  const trimmed = text.trim();
  return /[.!?…]$/.test(trimmed) ? trimmed : `${trimmed}.`;
}
